#!/usr/bin/env python3
"""Writes tests/gfx/nvn_api.inc: X(name, PFN type) for every NVN function that has a PFN typedef in the NVN header
(src/gfx/nvn/third_party/nvn/nvn.h). nvn_app.h turns the list into typed callers obtained through nvnBootstrapLoader.
    python scripts/gen_nvn_test_api.py
"""
import os, re
root = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
hdr = open(os.path.join(root, 'src/gfx/nvn/third_party/nvn/nvn.h'), encoding='utf-8').read()
tab = open(os.path.join(root, 'src/gfx/nvn/nvn_table.inc'), encoding='utf-8').read()
names = re.findall(r'NVN_ENTRY\("(nvn\w+)"', tab)
upper = {('PFN' + n.upper() + 'PROC'): n for n in names}
pfns = re.findall(r'typedef\s+[^;]*?\(\*(PFNNVN\w+PROC)\)', hdr, re.S)
out = []
for p in pfns:
    n = upper.get(p)
    if n and n not in ('nvnBootstrapLoader', 'nvnDeviceGetProcAddress'):
        out.append('X(%s, %s)' % (n, p))
open(os.path.join(root, 'tests/gfx/nvn_api.inc'), 'w').write('// Generated by scripts/gen_nvn_test_api.py: do not edit.\n' + '\n'.join(sorted(out)) + '\n')
print(len(out), 'functions')
