// Output pass (stream S14): draws the game's final picture into the swapchain (or the headless frame image) like the present pass of the NVN back end,
// but able to encode it for HDR and to upscale it first.
//
//   encode   mode 0 copy (the SDR picture as the game wrote it: sRGB-encoded bytes), 1 scene-linear to sRGB, 2 scene-linear to HDR10 (BT.2020, ST 2084),
//            3 scene-linear to scRGB. "Scene-linear" is the HDR scene pipeline's window texture: float16, 1.0 = paper white, values above 1 are highlights.
//   upscale  AMD FSR 1: EASU into a float16 image the size of the picture, then RCAS (sharpen), then the encode above reads that image. Used when the
//            picture on screen is larger than the source crop. In HDR scene mode both run on c = x / (1 + x), so highlights above 1 survive the filters.
//
// The shaders and their push-constant layouts are in extras_shaders.inc (generated by scripts/gen_extras_shaders.py).
#pragma once
#include <volk.h>

#include <cstdint>
#include <map>

#include "nxrt/extras.h"
#include "nxrt/gfx.h"
#include "extras/fsr1_spatial.h"

namespace nxrt::extras {

struct OutputParams {
    VkImageView src = VK_NULL_HANDLE;       // SHADER_READ_ONLY_OPTIMAL
    VkExtent2D src_extent = {};
    int32_t crop[4] = {0, 0, 0, 0};          // x, y, w, h in source texels (w or h 0: the whole source)
    bool keep_aspect = true;                 // letterbox instead of stretching
    bool flip_y = false;                     // lower-left window origin
    bool src_linear = false;                 // scene-linear float source (HDR scene) rather than sRGB-encoded bytes
    OutputKind out = OutputKind::Sdr8;       // what the destination carries
    float paper_white_nits = 203, peak_nits = 1000;
    bool fsr1 = false;                       // upscale with FSR 1 when the picture is larger than the source
    float sharpness = 0.8f;                  // 0..1 (RCAS)
};

class OutputPass {
public:
    OutputPass() = default;
    ~OutputPass() { shutdown(); }
    OutputPass(const OutputPass&) = delete;
    OutputPass& operator=(const OutputPass&) = delete;

    bool init(gfx::Device& dev);
    void shutdown();
    bool initialised() const { return dev_ != nullptr; }

    // Records into cb, outside any render pass: dst_view must be in COLOR_ATTACHMENT_OPTIMAL. Returns the encode mode used (for logs and tests).
    int record(VkCommandBuffer cb, VkImageView dst_view, VkFormat dst_format, VkExtent2D dst_extent, const OutputParams& p);

    // Counters for the log and the tests.
    uint32_t fsr_frames() const { return fsr_.frames(); }

    static constexpr uint32_t kSetRing = 16;

private:
    VkPipeline encode_pipeline(VkFormat fmt);
    void encode(VkCommandBuffer cb, VkImageView dst_view, VkFormat dst_format, VkExtent2D dst_extent, VkImageView src, VkExtent2D src_extent, const int32_t crop[4],
                bool keep_aspect, bool flip_y, int mode, float paper, float peak, VkImageLayout src_layout);

    gfx::Device* dev_ = nullptr;
    VkSampler linear_ = VK_NULL_HANDLE, nearest_ = VK_NULL_HANDLE;
    // encode (graphics)
    VkDescriptorSetLayout enc_set_layout_ = VK_NULL_HANDLE;
    VkPipelineLayout enc_layout_ = VK_NULL_HANDLE;
    VkShaderModule vs_ = VK_NULL_HANDLE, fs_ = VK_NULL_HANDLE;
    std::map<VkFormat, VkPipeline> enc_pipes_;
    VkDescriptorPool pool_ = VK_NULL_HANDLE;
    VkDescriptorSet enc_sets_[kSetRing] = {};
    uint32_t next_enc_ = 0;
    Fsr1Spatial fsr_;
};

}  // namespace nxrt::extras
