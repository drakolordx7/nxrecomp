"""Writes the lifter site list (recomp nxrecomp/program.py load_sites) of a test program: an `entryhook` line for each hook stub
the guest runtime header (tests/lift/guest/rt2.h) defines. The test driver attaches the runtime's functions to those addresses.

    python make_sites.py <prog.elf> <out.sites>
Stubs: _Unwind_RaiseException, _Unwind_Resume, nx_host_terminate (those present in the ELF)."""
import os
import subprocess
import sys

LLVM = os.environ.get('LLVM_BIN', r'C:\Program Files\LLVM\bin')
STUBS = ('_Unwind_RaiseException', '_Unwind_Resume', 'nx_host_terminate')


def main():
    elf, out = sys.argv[1], sys.argv[2]
    nm = subprocess.run([os.path.join(LLVM, 'llvm-nm.exe'), '--defined-only', elf], capture_output=True, text=True, check=True).stdout
    found = {}
    for line in nm.splitlines():
        parts = line.split()
        if len(parts) == 3 and parts[2] in STUBS:
            found[parts[2]] = int(parts[0], 16)
    with open(out, 'w') as f:
        f.write('# generated by make_sites.py: hook stubs of %s\n' % os.path.basename(elf))
        for name in STUBS:
            if name in found:
                f.write('entryhook %x    # %s\n' % (found[name], name))
    print('%s: %d entry hooks' % (out, len(found)))


if __name__ == '__main__':
    main()
