struct LogCapture {
    std::vector<std::string> lines;
    static void sink(LogLevel, const char* line, void* user) { static_cast<LogCapture*>(user)->lines.emplace_back(line); }
    LogCapture() { log_set_sink(&LogCapture::sink, this); }
    ~LogCapture() { log_set_sink(nullptr, nullptr); }
    bool has(const std::string& a, const std::string& b = "") const {
        for (auto& l : lines)
            if (l.find(a) != std::string::npos && l.find(b) != std::string::npos) return true;
        return false;
    }
};

// Calls the HLE thunk at addr with the guest registers in c, as the generated code's call_indirect would.
void call_thunk(::Ctx* c, uint64_t addr) { dispatch_call(c, addr); }

uint64_t bootstrap(const char* name) {
    ::Ctx c{};
    c.x[0] = reinterpret_cast<uint64_t>(name);
    c.x[30] = 0x7100000100;
    call_thunk(&c, hle_address("nvnBootstrapLoader"));
    return c.x[0];
}

uint64_t device_get_proc(const char* name) {
    ::Ctx c{};
    static char fake_device[0x3000];
    c.x[0] = reinterpret_cast<uint64_t>(fake_device);
    c.x[1] = reinterpret_cast<uint64_t>(name);
    c.x[30] = 0x7100000100;
    call_thunk(&c, hle_address("nvnDeviceGetProcAddress"));
    return c.x[0];
}

// Reads the pfnc_ names of the practice mod's header when the reference checkout is there (an independent list: the table was
// generated by a script from the same file, this reads it again with different code).
bool read_reference_names(std::set<std::string>* out) {
    const char* roots[] = {"C:/mpr/refs", "../../../refs", "../../../../refs"};
    const char* env = std::getenv("NXRT_REFS_DIR");
    std::vector<std::string> cands;
    if (env) cands.push_back(env);
    for (auto r : roots) cands.push_back(r);
    for (auto& root : cands) {
        std::ifstream f(root + "/mp1r-practice-mod/src_framework/nvn/nvn_FuncPtrBase.h");
        if (!f) continue;
        std::string line;
        while (std::getline(f, line)) {
            size_t p = line.find("pfnc_nvn");
            if (p == std::string::npos) continue;
            p += 5;
            size_t e = p;
            while (e < line.size() && (std::isalnum(static_cast<unsigned char>(line[e])) || line[e] == '_')) ++e;
            out->insert(line.substr(p, e - p));
        }
        if (!out->empty()) return true;
    }
    return false;
}

