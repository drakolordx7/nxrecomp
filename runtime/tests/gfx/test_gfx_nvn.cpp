NXTEST(table_is_complete_and_unique) {
    const size_t n = nvn::entry_count();
    std::printf("    %zu NVN entry points, %zu object sizes\n", n, [] { size_t c; nvn::struct_sizes(&c); return c; }());
    CHECK(n >= 477);
    std::set<std::string> names;
    size_t from_mpr = 0;
    for (size_t i = 0; i < n; ++i) {
        const nvn::Entry& e = nvn::entry_at(i);
        CHECK(std::strncmp(e.name, "nvn", 3) == 0);
        CHECK(names.insert(e.name).second);
        CHECK(e.sources != 0);
        CHECK(e.args != nullptr);
        if (e.sources & nvn::kSrcPracticeMod) ++from_mpr;
        CHECK_EQ(nvn::entry_index(e.name), static_cast<int>(i));
    }
    std::printf("    %zu of them are in the header used against this game\n", from_mpr);
    CHECK(from_mpr >= 477);
    CHECK_EQ(nvn::entry_index("nvnNotAnEntryPoint"), -1);
}

NXTEST(table_matches_the_reference_header) {
    std::set<std::string> ref;
    if (!read_reference_names(&ref)) {
        nxtest::skip("refs/mp1r-practice-mod not found (set NXRT_REFS_DIR)");
        return;
    }
    size_t missing = 0;
    for (auto& name : ref) {
        if (nvn::entry_index(name.c_str()) < 0) {
            std::printf("    missing from the table: %s\n", name.c_str());
            ++missing;
        }
    }
    std::printf("    reference header: %zu names, %zu missing\n", ref.size(), missing);
    CHECK_EQ(missing, 0u);
    CHECK(ref.size() >= 470);
}

NXTEST(bootstrap_loader_answers_every_entry_point) {
    nvn::install();
    size_t bad = 0;
    for (size_t i = 0; i < nvn::entry_count(); ++i) {
        const char* name = nvn::entry_at(i).name;
        const uint64_t a = bootstrap(name);
        const uint64_t b = device_get_proc(name);
        const bool ok = a != 0 && hle_is_thunk(a) && hle_name_at(a) && std::strcmp(hle_name_at(a), name) == 0 && a == b;
        if (!ok) {
            std::printf("    BAD %s: bootstrap=0x%llx devproc=0x%llx\n", name, static_cast<unsigned long long>(a), static_cast<unsigned long long>(b));
            ++bad;
        }
    }
    std::printf("    nvnBootstrapLoader and nvnDeviceGetProcAddress: %zu names answered, %zu bad\n", nvn::entry_count(), bad);
    CHECK_EQ(bad, 0u);
    CHECK_EQ(bootstrap(nullptr), 0ull);
    CHECK_EQ(bootstrap(""), 0ull);
}

NXTEST(stub_logs_name_arguments_and_caller) {
    nvn::install();
    nvn::reset_counters();
    LogCapture cap;
    const uint64_t a = bootstrap("nvnTextureBuilderSetSize2D");   // (builder*, int width, int height)
    REQUIRE(a != 0);
    ::Ctx c{};
    c.x[0] = 0x7A00001000;
    c.x[1] = 1024;
    c.x[2] = 0xFFFFFFFFFFFFFFFFull;   // w2 = -1 as an int: only the low 32 bits count
    c.x[30] = 0x7100ABCD04;          // return address: the call site is 4 before it
    c.x[5] = 0x1234;
    call_thunk(&c, a);
    CHECK_EQ(c.x[0], 0ull);
    CHECK_EQ(nvn::entry_calls(static_cast<size_t>(nvn::entry_index("nvnTextureBuilderSetSize2D"))), 1ull);
    CHECK(cap.has("nvnTextureBuilderSetSize2D", "p=0x7a00001000"));
    CHECK(cap.has("nvnTextureBuilderSetSize2D", "i=1024 i=-1"));
    CHECK(cap.has("nvnTextureBuilderSetSize2D", "caller=0x7100abcd00"));

    // float arguments come from the vector registers, not from x
    const uint64_t b = bootstrap("nvnSamplerBuilderSetLodClamp");   // (builder*, float min, float max)
    ::Ctx f{};
    f.x[0] = 0x7A00002000;
    f.v[0].f32[0] = 0.5f;
    f.v[1].f32[0] = 12.0f;
    f.x[30] = 0x7100000204;
    call_thunk(&f, b);
    CHECK(cap.has("nvnSamplerBuilderSetLodClamp", "f=0.5 f=12"));

    // a return value is 0 whatever the registers held (x0 and v0)
    const uint64_t g = bootstrap("nvnDeviceGetCurrentTimestampInNanoseconds");
    ::Ctx r{};
    r.x[0] = 0x7A00003000;
    r.x[30] = 0x7100000304;
    r.v[0].f32[0] = 3.0f;
    call_thunk(&r, g);
    CHECK_EQ(r.x[0], 0ull);
    CHECK_EQ(r.v[0].f32[0], 0.0f);
    CHECK(nvn::stub_calls_total() >= 3);
    CHECK_EQ(nvn::stubs_called_distinct(), 3u);
}

NXTEST(stub_goes_quiet_after_the_first_calls_but_keeps_counting) {
    nvn::install();
    nvn::reset_counters();
    LogCapture cap;
    const uint64_t a = bootstrap("nvnQueueFlush");
    REQUIRE(a != 0);
    for (int i = 0; i < 50; ++i) {
        ::Ctx c{};
        c.x[0] = 0x7A00004000;
        c.x[30] = 0x7100000404;
        call_thunk(&c, a);
    }
    CHECK_EQ(nvn::entry_calls(static_cast<size_t>(nvn::entry_index("nvnQueueFlush"))), 50ull);
    size_t info_lines = 0;
    for (auto& l : cap.lines)
        if (l.find("STUB nvnQueueFlush") != std::string::npos) ++info_lines;
    std::printf("    50 calls logged %zu lines at the default level\n", info_lines);
    CHECK_EQ(info_lines, 3u);   // [nvn] log_first_calls = 3
}

NXTEST(unknown_names_follow_the_policy) {
    nvn::install();
    nvn::set_unknown_policy(nvn::UnknownPolicy::Null);
    CHECK_EQ(bootstrap("nvnSomethingFromANewerDriver"), 0ull);
    CHECK_EQ(bootstrap("notAnNvnName"), 0ull);
    nvn::set_unknown_policy(nvn::UnknownPolicy::Stub);
    LogCapture cap;
    const uint64_t a = bootstrap("nvnSomethingFromANewerDriver");
    CHECK(a != 0);
    CHECK(cap.has("UNKNOWN NVN PROC", "nvnSomethingFromANewerDriver"));
    ::Ctx c{};
    c.x[0] = 7;
    c.x[30] = 0x7100000504;
    call_thunk(&c, a);
    CHECK_EQ(c.x[0], 0ull);
    CHECK(cap.has("UNKNOWN NVN PROC", "caller=0x7100000500"));
    CHECK_EQ(bootstrap("notAnNvnName"), 0ull);   // not an nvn name: null whatever the policy
    nvn::set_unknown_policy(nvn::UnknownPolicy::Stub);
}

namespace {
void impl_get_integer(::Ctx* c) { c->x[0] = 42; }
}  // namespace

NXTEST(register_impl_replaces_the_stub) {
    nvn::install();
    nvn::reset_counters();
    const size_t before = nvn::implemented_count();
    CHECK(!nvn::is_implemented("nvnDeviceGetInteger"));
    CHECK(!nvn::register_impl("nvnNotAnEntryPoint", impl_get_integer));
    CHECK(nvn::register_impl("nvnDeviceGetInteger", impl_get_integer));
    CHECK(nvn::is_implemented("nvnDeviceGetInteger"));
    CHECK_EQ(nvn::implemented_count(), before + 1);
    const uint64_t a = bootstrap("nvnDeviceGetInteger");
    ::Ctx c{};
    c.x[30] = 0x7100000604;
    call_thunk(&c, a);
    CHECK_EQ(c.x[0], 42ull);
    CHECK_EQ(nvn::entry_calls(static_cast<size_t>(nvn::entry_index("nvnDeviceGetInteger"))), 0ull);   // the stub counter is not touched
}

