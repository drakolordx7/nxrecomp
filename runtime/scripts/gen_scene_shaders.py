# Compiles src/gfx/shaders/scene.{vert,frag} with glslc (Vulkan SDK) into src/gfx/scene_shaders.inc (uint32 arrays).
# The .inc is committed, so building the runtime does not need the SDK. Run: python -I scripts/gen_scene_shaders.py
import os, shutil, struct, subprocess, sys
root = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
glslc = shutil.which("glslc") or r"C:\VulkanSDK\1.4.363.0\Bin\glslc.exe"
out = ["// GENERATED by scripts/gen_scene_shaders.py from src/gfx/shaders/*: do not edit\n"]
for name, var in (("scene.vert", "kSceneVert"), ("scene.frag", "kSceneFrag")):
    src = os.path.join(root, "src", "gfx", "shaders", name)
    spv = subprocess.run([glslc, "-O", "--target-env=vulkan1.3", "-o", "-", src], capture_output=True, check=True).stdout
    words = struct.unpack("<%dI" % (len(spv) // 4), spv)
    out.append("static const uint32_t %s[] = {\n" % var)
    for i in range(0, len(words), 8):
        out.append("    " + ", ".join("0x%08x" % w for w in words[i:i + 8]) + ",\n")
    out.append("};\n")
with open(os.path.join(root, "src", "gfx", "scene_shaders.inc"), "w", newline="\n") as f:
    f.write("".join(out))
print("wrote scene_shaders.inc")
