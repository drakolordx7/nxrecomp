# Compiles the runtime's own GLSL (src/gfx/shaders/*, and the test scene's in tests/gfx/scene/shaders) with glslc of the Vulkan SDK, checks each module with spirv-val and writes the
# committed .inc files of uint32 arrays, so building the runtime does not need the SDK. The SDK is found through VULKAN_SDK (set by its
# installer); glslc and spirv-val on PATH are the fallback.
#
#   python -I scripts/gen_shaders.py            regenerate every .inc
#   python -I scripts/gen_shaders.py extras     only the named targets (scene, mask_clear, extras)
#
# Exit 1, with nothing written for the failing target, when a shader fails to compile or validate.
import os, shutil, struct, subprocess, sys, tempfile

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
SHADERS = os.path.join(ROOT, "src", "gfx", "shaders")
SCENE_SHADERS = os.path.join(ROOT, "tests", "gfx", "scene", "shaders")
FSR_INC = os.path.join(ROOT, "third_party", "ffx_fsr1")


def sdk_tool(name):
    sdk = os.environ.get("VULKAN_SDK")
    if sdk:
        for sub in ("Bin", "bin"):
            for exe in (name + ".exe", name):
                p = os.path.join(sdk, sub, exe)
                if os.path.isfile(p):
                    return p
    p = shutil.which(name)
    if not p:
        sys.exit("%s not found: install the Vulkan SDK and set VULKAN_SDK (or put %s on PATH)" % (name, name))
    return p


def mask_clear_modules():
    mods = [("kMaskClearVert", "mask_clear.vert", [])]
    for gtype, k in (("vec4", 0), ("ivec4", 1), ("uvec4", 2)):   # (GLSL type, kind index as used by MaskClear::record)
        for loc in range(8):
            mods.append(("kMaskClearFrag_k%d_l%d" % (k, loc), "mask_clear.frag", ["-DTYPE=" + gtype, "-DLOC=%d" % loc]))
    return mods


def mask_clear_tail():
    # kMaskClearFrag[kind][location] -> blob. ShaderBlob is declared by the .cpp that includes the .inc.
    out = ["\nstatic const ShaderBlob kMaskClearFrag[3][8] = {\n"]
    for k in range(3):
        out.append("    {\n")
        for loc in range(8):
            var = "kMaskClearFrag_k%d_l%d" % (k, loc)
            out.append("        {%s, sizeof %s},\n" % (var, var))
        out.append("    },\n")
    out.append("};\n")
    out.append("static const ShaderBlob kMaskClearVertBlob = {kMaskClearVert, sizeof kMaskClearVert};\n")
    return "".join(out)


# target: output .inc, header text, modules (C name, source file in the target's folder, extra glslc arguments), text appended at the end;
# "dir" is the folder of the sources (default src/gfx/shaders)
TARGETS = {
    "scene": dict(out="tests/gfx/scene/scene_shaders.inc", dir=SCENE_SHADERS, header="", tail="",
                  modules=[("kSceneVert", "scene.vert", []), ("kSceneFrag", "scene.frag", [])]),
    "mask_clear": dict(out="src/gfx/nvn/mask_clear_shaders.inc", header="", tail=mask_clear_tail(), modules=mask_clear_modules()),
    "extras": dict(out="src/gfx/extras/extras_shaders.inc", header_file="extras_shaders_layout.txt", tail="",
                   modules=[("kOutVert", "fullscreen.vert", []), ("kOutEncodeFrag", "out_encode.frag", []),
                            ("kOverlayCompositeFrag", "overlay_composite.frag", []), ("kFsrEasuComp", "fsr_easu.comp", []),
                            ("kFsrRcasComp", "fsr_rcas.comp", [])]),
}


def compile_module(glslc, spirv_val, src_dir, src_name, args, tmp, label):
    src = os.path.join(src_dir, src_name)
    res = subprocess.run([glslc, "-O", "--target-env=vulkan1.3", "-I", FSR_INC] + args + ["-o", "-", src], capture_output=True)
    if res.returncode != 0:
        sys.stderr.write("glslc failed on %s:\n%s" % (label, res.stderr.decode(errors="replace")))
        return None
    if res.stderr:
        sys.stderr.write("glslc warnings on %s:\n%s" % (label, res.stderr.decode(errors="replace")))
    spv = res.stdout
    if len(spv) % 4:
        sys.stderr.write("%s: SPIR-V size is not a multiple of 4\n" % label)
        return None
    path = os.path.join(tmp, label + ".spv")
    with open(path, "wb") as f:
        f.write(spv)
    val = subprocess.run([spirv_val, "--target-env", "vulkan1.3", path], capture_output=True, text=True)
    if val.returncode != 0:
        sys.stderr.write("spirv-val failed on %s:\n%s\n" % (label, (val.stdout + val.stderr).strip()))
        return None
    return struct.unpack("<%dI" % (len(spv) // 4), spv)


def hex_words(name, words):
    lines = ["static const uint32_t %s[] = {\n" % name]
    for i in range(0, len(words), 8):
        lines.append("    " + ", ".join("0x%08x" % w for w in words[i:i + 8]) + ",\n")
    lines.append("};\n")
    return "".join(lines)


def build(name, t, glslc, spirv_val):
    src_dir = t.get("dir", SHADERS)
    body = ["// GENERATED by scripts/gen_shaders.py from %s: do not edit" % os.path.relpath(src_dir, ROOT).replace(os.sep, "/") + "\n"]
    if "header_file" in t:
        with open(os.path.join(SHADERS, t["header_file"]), encoding="utf-8") as f:
            body.append(f.read())
    with tempfile.TemporaryDirectory() as tmp:
        for cname, src_name, args in t["modules"]:
            words = compile_module(glslc, spirv_val, src_dir, src_name, args, tmp, cname)
            if words is None:
                return False
            body.append("\n" + hex_words(cname, words))
    body.append(t["tail"])
    out = os.path.join(ROOT, t["out"])
    with open(out, "w", newline="\n") as f:
        f.write("".join(body))
    print("wrote %s (%d modules)" % (t["out"], len(t["modules"])))
    return True


def main():
    names = sys.argv[1:] or list(TARGETS)
    bad = [n for n in names if n not in TARGETS]
    if bad:
        sys.exit("unknown target(s) %s; known: %s" % (", ".join(bad), ", ".join(TARGETS)))
    glslc, spirv_val = sdk_tool("glslc"), sdk_tool("spirv-val")
    ok = all([build(n, TARGETS[n], glslc, spirv_val) for n in names])
    sys.exit(0 if ok else 1)


if __name__ == "__main__":
    main()
