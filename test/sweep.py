HERE = Path(__file__).resolve().parent
ROOT = HERE.parents[1]
WORLD_ORDER = ["frigate", "tallon", "chozo", "magmoor", "phendrana", "mines", "crater"]
WORLD_TITLES = {"frigate": "Frigate Orpheon", "tallon": "Tallon Overworld", "chozo": "Chozo Ruins", "magmoor": "Magmoor Caverns",
                "phendrana": "Phendrana Drifts", "mines": "Phazon Mines", "crater": "Impact Crater"}
NOISE_FLAG = 3        # 16x16 blocks of colour noise in a screenshot that make the area a visual issue
STATUS_RANK = {"OK": 0, "visual issue": 1, "timeout": 2, "hang": 3, "crash": 4, "not reached": 5}
MARK_RE = re.compile(r"^\[\s*([\d.]+) \w \S+ [^\]]*\] script: SWEEP (\w+) (\S+)")
LINE_RE = re.compile(r"^\[\s*([\d.]+) ([A-Z]) (\S+) ([^\]]*)\] (.*)$")

# log lines (after the arrival marker) that make an area a "visual issue" or are worth listing; key -> regex
ISSUE_PATTERNS = {
    "missing shader": re.compile(r"no translated shader for block (\w+)"),
    "texture not uploaded": re.compile(r"nvn\.tex: texture \d+: not uploaded"),
    "unsupported NVN operation": re.compile(r"unsupported|not supported", re.I),
    "validation message": re.compile(r"VUID-|validation error", re.I),
}
UNKNOWN_PATTERNS = [
    ("SVC", re.compile(r"UNKNOWN SVC (0x[0-9A-Fa-f]+) \((\w+)\)")),
    ("IPC", re.compile(r"STUB SERVICE (\S+) cmd (\d+)")),
    ("ioctl", re.compile(r"nvdrv.*UNHANDLED.*?(ioctl[^,;]*)", re.I)),
    ("NVN", re.compile(r"nvn: (?:STUB|UNKNOWN NVN PROC) (\w+)")),
    ("HLE", re.compile(r"(?:hle stub called|has no host implementation)[: ]*(\S+)?", re.I)),
]


def run_dir_name(i):
    return f"run{i:03d}"


# ----------------------------------------------------------------------------------------------------------- regions

def load_areas(regions: Path):
    worlds, areas = {}, []
    for line in regions.read_text(encoding="utf-8").splitlines():
        if not line.strip() or line.startswith("#"):
            continue
        p = line.split("\t")
        if len(p) < 3:
            continue
        key, wg, ag = p[0], p[1], p[2]
        if not ag:
            worlds[key] = wg
            continue
        wkey = key.split("_", 1)[0]
        if key in ("frigate_start", "tallon_start") or wkey not in WORLD_ORDER:
            continue                      # alias rows point at areas listed under their real key
        areas.append({"key": key, "world": wkey, "world_guid": wg, "area_guid": ag})
    order = {w: i for i, w in enumerate(WORLD_ORDER)}
    areas.sort(key=lambda a: (order[a["world"]], a["key"]))
    return areas


# ----------------------------------------------------------------------------------------------------------- scripts

BOOT = """# generated by sweep.py: title -> New Game -> the Frigate, then the area tour
@timeout 0
@mash A every 90 until state >= 0 timeout=40000
@log SWEEP boot ready
300
"""


def script_for(areas, settle, warp_timeout, play_frames=2400):
    out = [BOOT, f"@timeout {warp_timeout}\n"]
    for a in areas:
        k = a["key"]
        out.append(f"@log SWEEP begin {k}\n@warp {a['world']} {k}\n@log SWEEP arrived {k}\n@shot {k}_arr\n@play {settle:g} timeout={play_frames} soft\n@shot {k}_a\n@hash {k}\n"
                   f"stick right 1.0 0 for 50\n30\n@shot {k}_b\n@log SWEEP ok {k}\n")
    out.append("@pass\n")
    return "".join(out)


# ----------------------------------------------------------------------------------------------------------- one process

class Job:
    def __init__(self, idx, areas, a, slot):
        self.idx, self.areas, self.a, self.slot = idx, areas, a, slot


def kill_tree(p):
    subprocess.run(["taskkill", "/F", "/T", "/PID", str(p.pid)], stdout=subprocess.DEVNULL, stderr=subprocess.DEVNULL)
    if p.poll() is None:
        p.kill()


def parse_log(path: Path):
    """-> (markers [(t, what, key)], lines [(t, level, tag, text)])"""
    marks, lines = [], []
    try:
        text = path.read_text(encoding="utf-8", errors="replace")
    except OSError:
        return marks, lines
    for ln in text.splitlines():
        m = MARK_RE.match(ln)
        if m:
            marks.append((float(m.group(1)), m.group(2), m.group(3)))
            continue
        m = LINE_RE.match(ln)
        if m:
            lines.append((float(m.group(1)), m.group(2), m.group(4).strip(), m.group(5)))
    return marks, lines


def run_process(a, job, run_id, areas, log):
    """Run one chunk. Returns dict(rc, wall, outdir, verdict, reason, boot_ok, marks, lines, result)."""
    outdir = a.out / "runs" / run_id
    if outdir.exists():
        shutil.rmtree(outdir, ignore_errors=True)
    outdir.mkdir(parents=True)
    script = outdir / "tour.nxs"
    script.write_text(script_for(areas, a.settle, a.warp_frames, a.play_frames), encoding="utf-8")
    cwd = a.out / "work" / f"slot{job.slot}"
    save = cwd / "save"
    shutil.rmtree(save, ignore_errors=True)
    cwd.mkdir(parents=True, exist_ok=True)
    env = dict(os.environ)
    env.update({
        "NXRT_GFX_HEADLESS": "1", "NXRT_BOOT_GFX": "headless",
        "NXRT_FS_ROMFS": str(ROOT / "game" / "romfs"), "NXRT_FS_SAVE_DIR": str(save),
        "NXRT_TEST_SCRIPT": str(script), "NXRT_TEST_OUT": str(outdir), "NXRT_TEST_REGIONS": str(a.regions),
        "NXRT_TEST_DETERMINISTIC": "1" if a.deterministic else "0", "NXRT_LOG_PATH": str(outdir / "mpr.log"),
        "NXRT_NVN_BC7_CACHE": str(a.cache), "NXRT_DIAG_WATCHDOG_SECONDS": str(a.watchdog), "NXRT_DIAG_FREEZE_RESAMPLE_S": "4",
        "NXRT_TEST_WALL_TIMEOUT_S": str(a.process_cap),
    })
    cmd = [str(a.exe), "--max-seconds", str(a.process_cap - 5)]
    t0 = time.monotonic()
    with open(outdir / "stdout.txt", "wb") as so, open(outdir / "stderr.txt", "wb") as se:
        p = subprocess.Popen(cmd, cwd=str(cwd), env=env, stdout=so, stderr=se)
        last_mark, last_count, stalled = time.monotonic(), 0, False
        booted = False
        while True:
            try:
                rc = p.wait(timeout=3)
                break
            except subprocess.TimeoutExpired:
                pass
            now = time.monotonic()
            logp = outdir / "mpr.log"
            try:
                txt = logp.read_text(encoding="utf-8", errors="replace")
            except OSError:
                txt = ""
            n = txt.count("script: SWEEP")
            if "script: SWEEP boot ready" in txt:
                booted = True
            if n != last_count:
                last_count, last_mark = n, now
            limit = a.area_stall if booted else a.boot_stall
            if now - last_mark > limit:
                stalled = True
                try:                                   # ask the process for a thread dump of its own (the watchdog polls this file), then end it
                    (a.exe.parent / f"dump_threads.{p.pid}").write_bytes(b"")
                    time.sleep(6)
                except OSError:
                    pass
                kill_tree(p)
                rc = p.wait()
                break
            if now - t0 > a.process_cap + 30:
                stalled = True
                kill_tree(p)
                rc = p.wait()
                break
    wall = time.monotonic() - t0
    marks, lines = parse_log(outdir / "mpr.log")
    result = None
    try:
        result = json.loads((outdir / "result.json").read_text(encoding="utf-8"))
    except (OSError, ValueError):
        pass
    verdict, reason = "ok", ""
    if rc == 0:
        verdict = "ok"
    elif rc == 4:
        verdict, reason = "crash", (result or {}).get("message", "host crash")
    elif rc == 5:
        verdict, reason = "hang", "watchdog freeze: no frame tick for %ss" % a.watchdog
    elif stalled:
        verdict, reason = "hang", "no progress for %d s (killed)" % (a.area_stall if booted else a.boot_stall)
    elif rc == 124:
        verdict, reason = "timeout", "process cap reached"
    elif rc == 1:
        verdict, reason = "timeout", (result or {}).get("message", "script failure")
    else:
        verdict, reason = "crash", "exit code %s" % rc
    if rc != 0 and any(l[1] == "E" and l[2] == "crash" for l in lines) and verdict != "crash":
        verdict = "crash"
    return {"rc": rc, "wall": wall, "outdir": outdir, "verdict": verdict, "reason": reason, "booted": any(m[1] == "boot" for m in marks), "marks": marks, "lines": lines, "result": result}


def summary_unknowns(lines):
    """Unknown-call tally from the end-of-run summary the runtime logs: unknown SVCs, unhandled IPC commands per service, HLE stubs called."""
    c = collections.Counter()
    for t, lvl, tag, text in lines:
        if "state at the end of the run" not in text and "state at the deadline" not in text and "end-of-run summary" not in text:
            continue
        m = re.search(r"svc: \d+ calls, \d+ distinct, (\d+) unknown", text)
        if m and int(m.group(1)):
            c["SVC unknown (end-of-run count)"] += int(m.group(1))
        for m in re.finditer(r"(\S+): \d+ requests, (\d+) unhandled commands", text):
            if int(m.group(2)):
                c["IPC unhandled " + m.group(1)] += int(m.group(2))
        for m in re.finditer(r"hle stub called (\d+)x: (\S+)", text):
            c["HLE stub " + m.group(2)] += int(m.group(1))
    return c


def crash_summary(lines):
    """First line of the crash report plus the guest call stack, from the log."""
    out = []
    for t, lvl, tag, text in lines:
        if tag == "crash" and text.strip():
            out.append(text.strip())
            if len(out) >= 12:
                break
    return out


def freeze_summary(lines):
    stack = []
    for t, lvl, tag, text in lines:
        if tag == "watchdog" and ("FREEZE" in text or "guest call stack" in text):
            stack.append(text.strip())
    return stack[:4]


# ----------------------------------------------------------------------------------------------------------- analysis

def noise_blocks(arr, blk=16):
    """Number of 16x16 blocks that look like colour noise: strong horizontal gradients whose R, G and B parts are uncorrelated (natural
    images and HUD art have correlated channels). Calibrated on the hangar-door and glass-panel noise of the first gameplay captures."""
    import numpy as np
    h, w, _ = arr.shape
    h -= h % blk
    dx = np.diff(arr[:h, :w].astype(np.float32), axis=1)
    ww = (dx.shape[1] // blk) * blk
    B = dx[:, :ww].reshape(h // blk, blk, ww // blk, blk, 3).transpose(0, 2, 1, 3, 4).reshape(h // blk, ww // blk, blk * blk, 3)
    mag = np.abs(B).mean(axis=(2, 3))

    def corr(x, y):
        xm = x - x.mean(axis=2, keepdims=True)
        ym = y - y.mean(axis=2, keepdims=True)
        return (xm * ym).sum(axis=2) / (np.sqrt((xm ** 2).sum(axis=2) * (ym ** 2).sum(axis=2)) + 1e-6)

    c = np.minimum(corr(B[..., 0], B[..., 1]), corr(B[..., 1], B[..., 2]))
    return int(((mag > 30) & (c < 0.5)).sum())


def image_stats(path: Path):
    try:
        import numpy as np
        from PIL import Image
        full = np.asarray(Image.open(path).convert("RGB"))
        small = full[::10, ::10].astype(np.float32)
        return {"mean": round(float(small.mean()), 1), "std": round(float(small.std()), 1), "noise_blocks": noise_blocks(full)}
    except Exception:
        return None


def analyse_area(key, marks, lines, outdir, next_t):
    """Per-area result from one process: the slice of the log between begin and the next area's begin."""
    t_begin = t_arr = t_ok = None
    for t, what, k in marks:
        if k == key:
            if what == "begin":
                t_begin = t
            elif what == "arrived":
                t_arr = t
            elif what == "ok":
                t_ok = t
    res = {"begin": t_begin, "arrived": t_arr, "ok": t_ok}
    if t_begin is None:
        return res
    end = next_t if next_t else 1e12
    sl = [l for l in lines if t_begin <= l[0] < end]
    issues = collections.Counter()
    detail = {}
    warn = collections.Counter()
    unknown = collections.Counter()
    for t, lvl, tag, text in sl:
        for name, rx in ISSUE_PATTERNS.items():
            m = rx.search(text)
            if m and lvl in "WE":
                issues[name] += 1
                if m.groups() and m.group(1):
                    detail.setdefault(name, set()).add(m.group(1))
        for kind, rx in UNKNOWN_PATTERNS:
            m = rx.search(text)
            if m:
                unknown[f"{kind} {' '.join(g for g in m.groups() if g)}".strip()] += 1
        if lvl in "WE":
            warn[re.sub(r"0x[0-9a-fA-F]+|\d+", "N", f"{tag}: {text}")[:120]] += 1
    res["stalled"] = any(tag == "script" and "SOFT-TIMEOUT" in text for t, lvl, tag, text in sl)
    res["issues"] = dict(issues)
    res["issue_detail"] = {k: sorted(v)[:6] for k, v in detail.items()}
    res["warnings"] = dict(warn.most_common(6))
    res["unknown_calls"] = dict(unknown)
    shots = {}
    for s in ("arr", "a", "b"):
        pth = outdir / "shots" / f"{key}_{s}.png"
        if pth.exists():
            shots[s] = {"path": pth.as_posix(), **(image_stats(pth) or {})}
    res["shots"] = shots
    if t_arr is not None and t_begin is not None:
        res["load_s"] = round(t_arr - t_begin, 1)
    return res


# ----------------------------------------------------------------------------------------------------------- sweep driver

class Sweep:
    def __init__(self, a, areas):
        self.a, self.areas = a, areas
        self.results = {}          # key -> dict
        self.lock = threading.Lock()
        self.runs = []             # per-process summaries
        self.run_counter = 0
        runs_dir = a.out / "runs"
        if runs_dir.exists():                      # keep the evidence of earlier sweeps: run numbers continue
            nums = [int(m.group(1)) for d in runs_dir.iterdir() for m in [re.fullmatch(r"run(\d+)", d.name)] if m]
            self.run_counter = max(nums, default=0)
        self.unknown = collections.Counter()
        self.slots = list(range(a.jobs))
        self.slot_lock = threading.Lock()
        self.crashes = []          # (key, text lines)

    def next_run_id(self):
        with self.lock:
            self.run_counter += 1
            return run_dir_name(self.run_counter)

    def take_slot(self):
        while True:
            with self.slot_lock:
                if self.slots:
                    return self.slots.pop(0)
            time.sleep(0.5)

    def give_slot(self, s):
        with self.slot_lock:
            self.slots.append(s)

    def record(self, key, **kw):
        with self.lock:
            self.results.setdefault(key, {}).update(kw)

    def save_partial(self):
        """results.json after every process, so a killed sweep keeps what it learned (--resume picks it up)."""
        with self.lock:
            data = {"meta": {"partial": True, "when": time.strftime("%Y-%m-%d %H:%M")}, "areas": self.results, "runs": self.runs, "unknown": dict(self.unknown)}
            tmp = self.a.out / "results.json.tmp"
            tmp.write_text(json.dumps(data, indent=1), encoding="utf-8")
            os.replace(tmp, self.a.out / "results.json")

    def process_chunk(self, chunk, label):
        """Run areas of one chunk; on failure restart after the failed area. Fills self.results."""
        a = self.a
        remaining = list(chunk)
        boot_failures = 0
        slot = self.take_slot()
        try:
            while remaining:
                job = Job(0, remaining, a, slot)
                rid = self.next_run_id()
                print(f"[{label}] run {rid}: {len(remaining)} areas starting at {remaining[0]['key']}", flush=True)
                r = run_process(a, job, rid, remaining, None)
                marks, lines = r["marks"], r["lines"]
                begun = [m for m in marks if m[1] == "begin"]
                booted = any(m[1] == "boot" for m in marks)
                oks = {m[2] for m in marks if m[1] == "ok"}
                with self.lock:
                    self.runs.append({"id": rid, "rc": r["rc"], "wall_s": round(r["wall"], 1), "verdict": r["verdict"], "areas": len(remaining),
                                      "reason": r["reason"], "dir": r["outdir"].as_posix()})
                    for kind, rx in UNKNOWN_PATTERNS:
                        pass
                begin_times = {m[2]: m[0] for m in marks if m[1] == "begin"}
                order = [x["key"] for x in remaining]
                for i, ar in enumerate(remaining):
                    key = ar["key"]
                    nxt = None
                    for j in range(i + 1, len(order)):
                        if order[j] in begin_times:
                            nxt = begin_times[order[j]]
                            break
                    if key in begin_times:
                        info = analyse_area(key, marks, lines, r["outdir"], nxt)
                        info.update({"run": rid, "evidence": r["outdir"].as_posix()})
                        if key in oks and info.get("stalled"):
                            info.update(status="hang", stage="play", reason="arrived, but the in-game clock never advanced (stuck in load or a cutscene)")
                        elif key in oks:
                            info["status"] = "OK"
                            iss = info.get("issues", {})
                            sa = info.get("shots", {}).get("a", {})
                            sb = info.get("shots", {}).get("b", {})
                            notes = []
                            if "missing shader" in iss:
                                notes.append("missing shader %s" % ",".join(info["issue_detail"].get("missing shader", [])))
                            if "texture not uploaded" in iss:
                                notes.append("%d texture(s) not uploaded" % iss["texture not uploaded"])
                            if "unsupported NVN operation" in iss:
                                notes.append("unsupported NVN operation x%d" % iss["unsupported NVN operation"])
                            if "validation message" in iss:
                                notes.append("validation messages x%d" % iss["validation message"])
                            for nm, sh in (("a", sa), ("b", sb)):
                                if sh and sh.get("mean", 99) < 2.0 and sh.get("std", 99) < 2.0:
                                    notes.append("shot %s is black" % nm)
                            nb = max(sa.get("noise_blocks", 0), sb.get("noise_blocks", 0))
                            if nb >= NOISE_FLAG:
                                notes.append("colour noise in %d blocks" % nb)
                            if notes:
                                info["status"] = "visual issue"
                            info["notes"] = notes
                        self.record(key, **info)
                    # not begun: handled below
                with self.lock:
                    pass
                failed_key = None
                if r["verdict"] != "ok":
                    # the failing area is the last one that began without ok; before boot finished it is none
                    started_not_ok = [x for x in order if x in begin_times and x not in oks]
                    failed_key = started_not_ok[0] if started_not_ok else None
                    if failed_key:
                        st = {"crash": "crash", "hang": "hang", "timeout": "timeout"}.get(r["verdict"], "crash")
                        extra = {}
                        if st == "crash":
                            extra["crash_report"] = crash_summary(lines)
                        if st == "hang":
                            extra["freeze_report"] = freeze_summary(lines)
                        # a timeout inside @warp / @play names the stage that never finished
                        stage = "warp" if not any(m[1] == "arrived" and m[2] == failed_key for m in marks) else "play"
                        self.record(failed_key, status=st, stage=stage, reason=r["reason"], run=rid, evidence=r["outdir"].as_posix(), exit_code=r["rc"], **extra)
                        remaining = order[order.index(failed_key) + 1:]
                        remaining = [x for x in chunk if x["key"] in remaining]
                    else:
                        boot_failures += 1
                        if boot_failures >= 2:
                            for ar in remaining:
                                self.record(ar["key"], status="not reached", reason="the game did not reach the Frigate (%s)" % r["reason"], run=rid,
                                            evidence=r["outdir"].as_posix())
                            remaining = []
                else:
                    remaining = [x for x in remaining if x["key"] not in oks and x["key"] not in begin_times]
                    if remaining:       # a clean exit that skipped areas should not happen; avoid an endless loop
                        for ar in remaining:
                            self.record(ar["key"], status="not reached", reason="script ended before the area", run=rid, evidence=r["outdir"].as_posix())
                        remaining = []
                done = sum(1 for x in chunk if x["key"] in self.results and "status" in self.results[x["key"]])
                self.save_partial()
                print(f"[{label}] {rid} -> {r['verdict']} ({r['wall']:.0f}s), {done}/{len(chunk)} areas recorded", flush=True)
                with self.lock:
                    for k, v in self.unknown_from(lines).items():
                        self.unknown[k] += v
                    for k, v in summary_unknowns(lines).items():
                        self.unknown[k] += v
        finally:
            self.give_slot(slot)

    @staticmethod
    def unknown_from(lines):
        c = collections.Counter()
        for t, lvl, tag, text in lines:
            for kind, rx in UNKNOWN_PATTERNS:
                m = rx.search(text)
                if m:
                    c[f"{kind} {' '.join(g for g in m.groups() if g)}".strip()] += 1
        return c

    def confirm_failures(self):
        """Rerun each failed area alone in a fresh process: tells a reproducible failure from one that depends on the preceding areas."""
        a = self.a
        bad = [k for k, v in self.results.items() if v.get("status") in ("crash", "hang", "timeout")]
        if not bad or not a.confirm:
            return
        amap = {x["key"]: x for x in self.areas}
        print(f"confirming {len(bad)} failed areas alone", flush=True)

        def one(key):
            slot = self.take_slot()
            try:
                rid = self.next_run_id()
                r = run_process(a, Job(0, [amap[key]], a, slot), rid, [amap[key]], None)
                oks = {m[2] for m in r["marks"] if m[1] == "ok"}
                with self.lock:
                    self.results[key]["alone"] = "OK" if key in oks else r["verdict"]
                    self.results[key]["alone_evidence"] = r["outdir"].as_posix()
                    self.runs.append({"id": rid, "rc": r["rc"], "wall_s": round(r["wall"], 1), "verdict": r["verdict"], "areas": 1, "reason": r["reason"],
                                      "dir": r["outdir"].as_posix(), "confirm": key})
                if key in oks:
                    info = analyse_area(key, r["marks"], r["lines"], r["outdir"], None)
                    with self.lock:
                        self.results[key]["alone_info"] = {k: info.get(k) for k in ("load_s", "shots")}
                print(f"  {key}: alone -> {'OK' if key in oks else r['verdict']}", flush=True)
            finally:
                self.give_slot(slot)

        with ThreadPoolExecutor(max_workers=a.jobs) as ex:
            list(ex.map(one, bad))


