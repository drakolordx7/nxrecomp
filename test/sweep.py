def md_escape(s):
    return str(s).replace("|", "/").replace("\n", " ")


def rel(p, root):
    try:
        return Path(p).resolve().relative_to(root).as_posix()
    except Exception:
        return str(p)


def reclassify(v):
    """Status of an area that ran, from what was recorded (so a rule change applies to old results at report time). A few textures drawn before
    their data arrived (the streaming order at every load) are a note, not a visual issue; black or noisy screenshots, a missing shader,
    validation messages and unsupported operations are."""
    if v.get("status") not in ("OK", "visual issue"):
        return v
    iss = v.get("issues", {})
    notes, bad = [], False
    if "missing shader" in iss:
        notes.append("missing shader %s" % ",".join(v.get("issue_detail", {}).get("missing shader", [])))
        bad = True
    if iss.get("texture not uploaded"):
        notes.append("%d texture(s) drawn before their data arrived" % iss["texture not uploaded"])
        bad = bad or iss["texture not uploaded"] >= 100
    if "unsupported NVN operation" in iss:
        notes.append("unsupported NVN operation x%d" % iss["unsupported NVN operation"])
        bad = True
    if "validation message" in iss:
        notes.append("validation messages x%d" % iss["validation message"])
        bad = True
    nb = 0
    for nm in ("arr", "a", "b"):
        sh = v.get("shots", {}).get(nm)
        if not sh:
            continue
        if nm != "arr" and sh.get("mean", 99) < 2.0 and sh.get("std", 99) < 2.0:
            notes.append("shot %s is black" % nm)
            bad = True
        nb = max(nb, sh.get("noise_blocks", 0)) if nm != "arr" else nb
    if nb >= NOISE_FLAG:
        notes.append("colour noise in %d blocks" % nb)
        bad = True
    v["notes"] = notes
    v["status"] = "visual issue" if bad else "OK"
    return v


def write_report(a, areas, results, runs, unknown, meta):
    for _v in results.values():
        reclassify(_v)
    by_world = collections.OrderedDict((w, []) for w in WORLD_ORDER)
    for ar in areas:
        by_world[ar["world"]].append(ar)
    counts = collections.Counter()
    for ar in areas:
        counts[results.get(ar["key"], {}).get("status", "not reached")] += 1
    total = len(areas)
    reached = total - counts["not reached"]
    L = []
    L.append("# Full-game sweep\n")
    L.append("Generated by `tools\\test\\sweep.py` (S15). Every area of `tools\\test\\regions.tsv` is warped to from the Frigate with the practice-mod "
             "warp sequence, the game stands for a few seconds of play time, the camera turns with the right stick, and two screenshots and a state hash are "
             "taken. Rerun the whole sweep with one command:\n")
    L.append("```\ntools\\.venv\\Scripts\\python tools\\test\\sweep.py --exe game-build\\build\\release\\mpr.exe --jobs 2\n```\n")
    L.append("`--resume` keeps the areas that were OK last time, `--report-only` rebuilds this file from `work\\sweep_out\\results.json`, `--worlds`, `--areas` and "
             "`--limit` select a subset.\n")
    L.append(f"Last sweep: {meta.get('when', '?')}, exe `{meta.get('exe', '?')}`, {meta.get('wall_min', '?')} min wall, {meta.get('jobs', '?')} parallel.\n")
    L.append("## Result\n")
    L.append(f"**{reached} of {total} areas reached.** " + ", ".join(f"{counts[s]} {s}" for s in
             ("OK", "visual issue", "timeout", "hang", "crash", "not reached") if counts[s]) + ".\n")
    L.append("| World | Areas | OK | Visual issue | Timeout | Hang | Crash | Not reached |\n|---|---|---|---|---|---|---|---|")
    for w, lst in by_world.items():
        if not lst:
            continue
        c = collections.Counter(results.get(x["key"], {}).get("status", "not reached") for x in lst)
        L.append(f"| {WORLD_TITLES[w]} | {len(lst)} | {c['OK']} | {c['visual issue']} | {c['timeout']} | {c['hang']} | {c['crash']} | {c['not reached']} |")
    L.append("")
    L.append("Status meanings: **OK** warp arrived, play time advanced, screenshots not black, no shader or texture errors in the log slice. **visual issue** arrived "
             "and ran, but a screenshot is black or has patches of colour noise, or the log shows a missing shader, a texture that was not uploaded or an unsupported NVN operation (owner: "
             "NVN back end). **timeout** the area never became current or play time never advanced. **hang** the watchdog saw no frame for too long, or "
             "nothing moved for minutes. **crash** the host or the guest crashed. **not reached** never started.\n")
    fails = [(k, v) for k, v in results.items() if v.get("status") in ("crash", "hang", "timeout")]
    if fails:
        L.append("## Failures\n")
        L.append("| Area | Status | Stage | Alone | Reason | Evidence |\n|---|---|---|---|---|---|")
        for k, v in sorted(fails, key=lambda kv: kv[0]):
            L.append(f"| {k} | {v['status']} | {v.get('stage', '')} | {v.get('alone', '-')} | {md_escape(v.get('reason', ''))[:100]} | `{rel(v.get('evidence', ''), ROOT)}` |")
        L.append("")
    for w, lst in by_world.items():
        if not lst:
            continue
        L.append(f"## {WORLD_TITLES[w]}\n")
        L.append("| Area | Status | Load s | Notes | Evidence |\n|---|---|---|---|---|")
        for ar in lst:
            v = results.get(ar["key"], {})
            st = v.get("status", "not reached")
            notes = "; ".join(v.get("notes", [])) if st in ("OK", "visual issue") else md_escape(v.get("reason", ""))
            ev = ""
            if v.get("shots", {}).get("b"):
                ev = f"`{rel(v['shots']['b']['path'], ROOT)}`"
            elif v.get("evidence"):
                ev = f"`{rel(v['evidence'], ROOT)}`"
            L.append(f"| {ar['key']} | {st} | {v.get('load_s', '')} | {md_escape(notes)} | {ev} |")
        L.append("")
    L.append("## Unknown calls\n")
    if unknown:
        L.append("Unknown SVC, IPC, ioctl, NVN and HLE stubs seen anywhere in the sweep, with log line counts:\n")
        L.append("| Call | Count |\n|---|---|")
        for k, c in sorted(unknown.items(), key=lambda kv: -kv[1])[:60]:
            L.append(f"| {md_escape(k)} | {c} |")
        L.append("")
    else:
        L.append("None logged.\n")
    L.append("## Processes\n")
    L.append("| Run | Result | Wall s | Areas | Note |\n|---|---|---|---|---|")
    for r in runs:
        L.append(f"| {r['id']}{' (alone: ' + r['confirm'] + ')' if r.get('confirm') else ''} | {r['verdict']} | {r['wall_s']} | {r['areas']} | {md_escape(r['reason'])[:90]} |")
    L.append("")
    a.md.parent.mkdir(parents=True, exist_ok=True)
    a.md.write_text("\n".join(L), encoding="utf-8")
    print(f"wrote {a.md}")


def contact_sheets(a, areas, results):
    try:
        from PIL import Image, ImageDraw
    except ImportError:
        return
    sheets = a.out / "sheets"
    sheets.mkdir(parents=True, exist_ok=True)
    for w in WORLD_ORDER:
        items = [(x["key"], results.get(x["key"], {})) for x in areas if x["world"] == w]
        items = [(k, v) for k, v in items if v.get("shots", {}).get("b")]
        if not items:
            continue
        cols, tw, th = 5, 384, 216
        rows = (len(items) + cols - 1) // cols
        sheet = Image.new("RGB", (cols * tw, rows * (th + 14)), (30, 30, 30))
        d = ImageDraw.Draw(sheet)
        for i, (k, v) in enumerate(items):
            try:
                im = Image.open(v["shots"]["b"]["path"]).convert("RGB").resize((tw, th))
            except Exception:
                continue
            x, y = (i % cols) * tw, (i // cols) * (th + 14)
            sheet.paste(im, (x, y + 14))
            d.text((x + 3, y + 1), f"{k} [{v.get('status', '')}]", fill=(255, 255, 0))
        sheet.save(sheets / f"{w}.png")


def main():
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--exe", default=os.environ.get("MPR_EXE") or str(ROOT / "game-build" / "build" / "release" / "mpr.exe"))
    ap.add_argument("--jobs", type=int, default=2)
    ap.add_argument("--chunk", type=int, default=12)
    ap.add_argument("--worlds")
    ap.add_argument("--areas")
    ap.add_argument("--limit", type=int, default=0)
    ap.add_argument("--settle", type=float, default=3.0)
    ap.add_argument("--resume", action="store_true")
    ap.add_argument("--no-confirm", dest="confirm", action="store_false")
    ap.add_argument("--report-only", action="store_true")
    ap.add_argument("--out", default=str(ROOT / "work" / "sweep_out"))
    ap.add_argument("--md", default=str(ROOT / "docs" / "mpr" / "SWEEP.md"))
    ap.add_argument("--regions", default=str(HERE / "regions.tsv"))
    ap.add_argument("--deterministic", action="store_true")
    ap.add_argument("--watchdog", type=int, default=60, help="seconds without a frame before the watchdog calls a freeze")
    ap.add_argument("--warp-frames", dest="warp_frames", type=int, default=30000, help="script timeout (game frames) of every wait")
    ap.add_argument("--play-frames", dest="play_frames", type=int, default=2400, help="game frames the play-time wait after arriving may take before the area counts as stalled")
    ap.add_argument("--boot-stall", dest="boot_stall", type=int, default=420, help="seconds without the boot reaching the Frigate before the run is killed")
    ap.add_argument("--area-stall", dest="area_stall", type=int, default=300, help="seconds without any area progress before the run is killed")
    ap.add_argument("--process-cap", dest="process_cap", type=int, default=3600)
    ap.add_argument("--cache", default=str(ROOT / "work" / "sweep_cache" / "bc7"))
    a = ap.parse_args()
    a.exe, a.out, a.md, a.regions, a.cache = (Path(x).resolve() for x in (a.exe, a.out, a.md, a.regions, a.cache))
    areas = load_areas(a.regions)
    if a.worlds:
        ws = {w.strip() for w in a.worlds.split(",")}
        areas = [x for x in areas if x["world"] in ws]
    if a.areas:
        rx = re.compile(a.areas)
        areas = [x for x in areas if rx.search(x["key"])]
    if a.limit:
        areas = areas[:a.limit]
    results_path = a.out / "results.json"
    prev = {}
    if results_path.exists():
        try:
            prev = json.loads(results_path.read_text(encoding="utf-8"))
        except ValueError:
            prev = {}
    full_areas = load_areas(a.regions)
    if a.report_only:
        write_report(a, full_areas, prev.get("areas", {}), prev.get("runs", []), collections.Counter(prev.get("unknown", {})), prev.get("meta", {}))
        return 0
    a.out.mkdir(parents=True, exist_ok=True)
    if not (a.resume or a.worlds or a.areas or a.limit):
        shutil.rmtree(a.out / "runs", ignore_errors=True)       # a complete fresh sweep replaces the old evidence
    a.cache.mkdir(parents=True, exist_ok=True)
    if not a.exe.exists():
        print(f"no such exe: {a.exe}", file=sys.stderr)
        return 2
    sw = Sweep(a, areas)
    keep = {}
    if a.resume:
        for k, v in prev.get("areas", {}).items():
            if v.get("status") == "OK":
                keep[k] = v
        areas = [x for x in areas if x["key"] not in keep]
        sw.areas = areas
    elif prev.get("areas"):
        # a partial run (subset selected) keeps the other areas' previous results in the report
        sel = {x["key"] for x in areas}
        keep = {k: v for k, v in prev["areas"].items() if k not in sel}
    sw.results.update({k: dict(v) for k, v in keep.items()})
    chunks = []
    for w in WORLD_ORDER:
        ws = [x for x in areas if x["world"] == w]
        for i in range(0, len(ws), a.chunk):
            chunks.append(ws[i:i + a.chunk])
    print(f"{len(areas)} areas in {len(chunks)} chunks, {a.jobs} parallel, exe {a.exe}", flush=True)
    t0 = time.time()
    if a.jobs > 1 or True:
        with ThreadPoolExecutor(max_workers=a.jobs) as ex:
            futs = [ex.submit(sw.process_chunk, c, f"c{i}") for i, c in enumerate(chunks)]
            for f in futs:
                f.result()
    sw.confirm_failures()
    wall = (time.time() - t0) / 60
    meta = {"when": time.strftime("%Y-%m-%d %H:%M"), "exe": rel(a.exe, ROOT), "wall_min": round(wall, 1), "jobs": a.jobs}
    all_results = sw.results
    full = load_areas(a.regions)
    for x in full:
        all_results.setdefault(x["key"], {"status": "not reached", "reason": "not selected in this sweep"}) if False else None
    old_runs = prev.get("runs", []) if (a.resume or keep) else []
    unknown = collections.Counter(prev.get("unknown", {})) if (a.resume or keep) else collections.Counter()
    unknown.update(sw.unknown)
    runs = old_runs + sw.runs
    results_path.write_text(json.dumps({"meta": meta, "areas": all_results, "runs": runs, "unknown": dict(unknown)}, indent=1), encoding="utf-8")
    contact_sheets(a, full, all_results)
    write_report(a, full, all_results, runs, unknown, meta)
    bad = [k for k, v in all_results.items() if v.get("status") in ("crash", "hang", "timeout", "not reached") and k in {x["key"] for x in areas}]
    print(f"done in {wall:.1f} min: " + ", ".join(f"{n} {s}" for s, n in collections.Counter(v.get("status", "?") for v in all_results.values()).items()))
    return 1 if bad else 0


if __name__ == "__main__":
    sys.exit(main())
