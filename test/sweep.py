#!/usr/bin/env python3
"""Full-game stability sweep (S15): warp to every area of tools\\test\\regions.tsv, stand, rotate the camera, take two screenshots and a
state hash, and record one status per area. One command rebuilds docs\\mpr\\SWEEP.md.

  tools\\.venv\\Scripts\\python tools\\test\\sweep.py [options]

  --exe PATH        mpr.exe to run (default game-build\\build\\release\\mpr.exe; env MPR_EXE)
  --jobs N          chunks run in parallel, each in its own work dir (default 2; the GPU is shared)
  --chunk N         areas per process (default 12); a crash or hang ends the process, the sweep restarts after the failed area
  --worlds a,b      only these worlds (frigate, tallon, chozo, magmoor, phendrana, mines, crater)
  --areas REGEX     only areas whose key matches
  --limit N         only the first N selected areas (smoke runs)
  --settle S        seconds of play time to stand after arriving (default 3)
  --resume          keep the OK results of the previous sweep (work\\sweep_out\\results.json) and run only the rest
  --no-confirm      do not rerun a failed area alone in a fresh process
  --report-only     rebuild SWEEP.md from results.json, run nothing
  --out DIR         output folder (default work\\sweep_out); --md PATH (default docs\\mpr\\SWEEP.md)
  --deterministic   run with the virtual clock (default off: the game steps by real time and loads from threads)

Per area: status OK / visual issue / hang / crash / timeout / not reached, load time, notes, evidence folder. Screenshots and saves stay under
work\\ (never in git). Exit code 0 when every selected area is OK or only has a visual issue, 1 otherwise.
"""
