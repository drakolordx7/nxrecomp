#!/usr/bin/env python3
"""Generate regions.tsv: world and area GUID table for scripted runs.

Reads the practice mod's RegionEntries.h (area arrays) and WarpMenu.cpp (world
GUIDs and the drawAreaEntries calls that tie each array to a world), then writes
one TSV line per world, per area and per start-room alias.

Usage: gen_regions.py [RegionEntries.h] [WarpMenu.cpp] [--out PATH]
"""
import argparse
import re
import sys
from pathlib import Path

DEFAULT_REGIONS = Path(r"D:\AI\Active\Metroid-Prime\refs\mp1r-practice-mod\src\program\RegionEntries.h")
DEFAULT_WARP = Path(r"D:\AI\Active\Metroid-Prime\refs\mp1r-practice-mod\src\program\WarpMenu.cpp")
DEFAULT_OUT = Path(__file__).resolve().parent / "regions.tsv"

# Display name used in drawWarpMenu -> world key used in the table.
WORLD_KEYS = {
    "Tallon Overworld": "tallon",
    "Chozo Ruins": "chozo",
    "Magmoor Caverns": "magmoor",
    "Phendrana Drifts": "phendrana",
    "Phazon Mines": "mines",
    "Impact Crater": "crater",
    "Space Pirate Frigate": "frigate",
}

HEADER = [
    "# regions.tsv: world and area GUID table for scripted runs.",
    "# Generated by gen_regions.py from RegionEntries.h and WarpMenu.cpp. Do not edit by hand.",
    "# Columns: key<TAB>world_guid<TAB>area_guid. World rows have an empty area_guid column.",
    "# Area rows are <world_key>_<area_key>. Alias rows (frigate_start, tallon_start) point at start rooms.",
]

GUID_RE = re.compile(r"^[0-9a-fA-F]{8}-[0-9a-fA-F]{4}-[0-9a-fA-F]{4}-[0-9a-fA-F]{4}-[0-9a-fA-F]{12}$")
ARRAY_RE = re.compile(r"RegionEntry\s+(\w+)\s*\[\s*\]\s*=\s*\{(.*?)^\};", re.S | re.M)
ENTRY_RE = re.compile(r'^\s*\{\s*"((?:[^"\\]|\\.)*)"\s*,\s*CObjectId\("([^"]*)"\)\s*\}\s*,?\s*$')
WORLD_DEF_RE = re.compile(r'CObjectId\s+(\w+)\s*=\s*CObjectId\("([^"]*)"\)\s*;\s*//\s*(.+?)[ \t]*$', re.M)
DRAW_RE = re.compile(r'drawAreaEntries\(\s*"([^"]+)"\s*,\s*(\w+)\s*,\s*(\w+)\s*\)')


class GenError(Exception):
    def __init__(self, messages):
        super().__init__("\n".join(messages))
        self.messages = messages


def make_key(text):
    return re.sub(r"[^a-z0-9]+", "_", text.lower()).strip("_")


def unique(key, used):
    if key not in used:
        used.add(key)
        return key
    i = 2
    while f"{key}_{i}" in used:
        i += 1
    new = f"{key}_{i}"
    used.add(new)
    return new


def parse_arrays(text, errors):
    arrays = {}
    for m in ARRAY_RE.finditer(text):
        name, body = m.group(1), m.group(2)
        entries = []
        for line in body.splitlines():
            if not line.strip():
                continue
            em = ENTRY_RE.match(line)
            if em is None:
                errors.append(f"{name}: unparseable entry line: {line.strip()}")
                continue
            entries.append((em.group(1).strip(), em.group(2)))
        arrays[name] = entries
    return arrays


def parse_worlds(text):
    # var name -> (label from trailing comment, guid string)
    return {var: (label, guid) for var, guid, label in WORLD_DEF_RE.findall(text)}


def build(regions_path, warp_path):
    errors = []
    arrays = parse_arrays(regions_path.read_text(encoding="utf-8"), errors)
    warp_text = warp_path.read_text(encoding="utf-8")
    worlds = parse_worlds(warp_text)

    # Map each entries array to its world through drawAreaEntries(display, worldVar, arrayVar).
    mapped = {}
    world_order = []  # (world_key, world_guid_raw, array_name)
    for display, world_var, array_name in DRAW_RE.findall(warp_text):
        if display not in WORLD_KEYS:
            errors.append(f"drawAreaEntries display name not in WORLD_KEYS: {display}")
            continue
        if world_var not in worlds:
            errors.append(f"{display}: world GUID {world_var} not defined in WarpMenu.cpp")
            continue
        label, wguid = worlds[world_var]
        if label != display:
            errors.append(f"{world_var}: comment label '{label}' does not match draw name '{display}'")
        if array_name not in arrays:
            errors.append(f"{display}: entries array {array_name} not found in RegionEntries.h")
            continue
        if array_name in mapped:
            errors.append(f"{array_name} is drawn for more than one world")
            continue
        mapped[array_name] = WORLD_KEYS[display]
        world_order.append((WORLD_KEYS[display], wguid, array_name))

    for name in arrays:
        if name not in mapped:
            errors.append(f"entries array {name} is not mapped to any world")

    if errors:
        raise GenError(errors)

    used = set()
    rows = []
    world_areas = {}  # world_key -> [(english name, area row key, area guid)]
    world_guids = {}  # world_key -> lower-case world guid
    counts = []

    for wkey, wguid_raw, array_name in world_order:
        if not GUID_RE.match(wguid_raw):
            errors.append(f"malformed world GUID for {wkey}: {wguid_raw}")
            continue
        wguid = wguid_raw.lower()
        world_guids[wkey] = wguid
        rows.append((unique(wkey, used), wguid, ""))
        world_areas[wkey] = []
        for name, aguid_raw in arrays[array_name]:
            if not GUID_RE.match(aguid_raw):
                errors.append(f"malformed area GUID in {array_name} for '{name}': {aguid_raw}")
                continue
            base = make_key(name)
            if not base:
                errors.append(f"empty area key for '{name}' in {array_name}")
                continue
            akey = unique(f"{wkey}_{base}", used)
            aguid = aguid_raw.lower()
            rows.append((akey, wguid, aguid))
            world_areas[wkey].append((name, akey, aguid))
        counts.append((wkey, len(world_areas[wkey])))

    if errors:
        raise GenError(errors)

    # Start-room aliases.
    frig = world_areas.get("frigate", [])
    if frig:
        start = next((e for e in frig if e[0].startswith("Emergency Evacuation")), frig[0])
        rows.append((unique("frigate_start", used), world_guids["frigate"], start[2]))
        print(f"frigate_start -> {start[0]}")
    tall = [e for e in world_areas.get("tallon", []) if e[0] == "Landing Site"]
    if tall:
        rows.append((unique("tallon_start", used), world_guids["tallon"], tall[0][2]))
        print("tallon_start -> Landing Site")
    else:
        print("note: no 'Landing Site' in Tallon Overworld; tallon_start not emitted", file=sys.stderr)

    return rows, counts


def main(argv=None):
    ap = argparse.ArgumentParser(description="Generate regions.tsv from the mod source.")
    ap.add_argument("regions", nargs="?", default=str(DEFAULT_REGIONS), help="path to RegionEntries.h")
    ap.add_argument("warp", nargs="?", default=str(DEFAULT_WARP), help="path to WarpMenu.cpp")
    ap.add_argument("--out", default=str(DEFAULT_OUT), help="output TSV path (default: regions.tsv beside this script)")
    args = ap.parse_args(argv)

    try:
        rows, counts = build(Path(args.regions), Path(args.warp))
    except GenError as e:
        for msg in e.messages:
            print(f"error: {msg}", file=sys.stderr)
        return 1
    except OSError as e:
        print(f"error: {e}", file=sys.stderr)
        return 1

    with open(args.out, "w", encoding="utf-8", newline="\n") as f:
        for line in HEADER:
            f.write(line + "\n")
        for row in rows:
            f.write("\t".join(row) + "\n")

    for wkey, n in counts:
        print(f"{wkey}: {n} areas")
    print(f"total rows: {len(rows)} -> {args.out}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
