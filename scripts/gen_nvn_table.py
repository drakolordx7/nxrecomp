QUAL = {"const", "volatile", "restrict", "__restrict", "static", "extern", "inline", "__inline"}
PRIM = {"char", "short", "int", "long", "unsigned", "signed", "_Bool", "bool", "float", "double", "void"}
FIXED_L = {"int64_t", "uint64_t", "size_t", "ssize_t", "ptrdiff_t", "intptr_t", "uintptr_t"}
FIXED_I = {"int8_t", "uint8_t", "int16_t", "uint16_t", "int32_t", "uint32_t"}
# Byte sizes of plain C scalar spellings (LP64, as on AArch64).
CSIZE = {
    "char": 1, "signed char": 1, "unsigned char": 1, "_Bool": 1, "bool": 1,
    "int8_t": 1, "uint8_t": 1,
    "short": 2, "unsigned short": 2, "int16_t": 2, "uint16_t": 2,
    "int": 4, "signed int": 4, "unsigned int": 4, "unsigned": 4, "signed": 4, "float": 4,
    "int32_t": 4, "uint32_t": 4,
    "long": 8, "unsigned long": 8, "long long": 8, "unsigned long long": 8, "double": 8,
    "int64_t": 8, "uint64_t": 8, "size_t": 8, "ssize_t": 8, "ptrdiff_t": 8,
    "intptr_t": 8, "uintptr_t": 8,
}

COMMENT_BLOCK = re.compile(r"/\*.*?\*/", re.S)
COMMENT_LINE = re.compile(r"//[^\n]*")
PP_LINE = re.compile(r"^[ \t]*#[^\n]*", re.M)
STRUCT_TD = re.compile(r"typedef\s+(struct|union|enum)\s*(\w*)\s*\{([^{}]*)\}\s*(\w+)\s*;", re.S)
PFN_TD = re.compile(r"typedef\s+([^;(){}]+?)\s*\(\s*\*\s*(\w+)\s*\)\s*\(([^;]*?)\)\s*;", re.S)
SIMPLE_TD = re.compile(r"typedef\s+([^;{}()]+?)\s+(\w+)\s*;")
ENUM_TAG = re.compile(r"\benum\s+(\w+)\s*\{")
EXTERN_RE = re.compile(r"extern\s+(PFNNVN\w+)\s+pfnc_(nvn\w+)\s*;")
PROTO_RE = re.compile(r"([A-Za-z_][\w \t\*]*?)\s+(nvn\w+)\s*\(([^;]*?)\)\s*;")
STR_NVN = re.compile(r'"(nvn[A-Z]\w*)"')
TOKEN_NVN = re.compile(r"\bnvn[A-Z]\w*")
CLAIM_PAREN = re.compile(r"\b(NVN[A-Za-z]+)\s*\(\s*(0x[0-9a-fA-F]+|\d+)\s*\)")
CLAIM_HEX = re.compile(r"\b(NVN[A-Za-z]+)\b[^\n]{0,30}?\b(0x[0-9a-fA-F]+)\b")


def read_text(path):
    with open(path, encoding="utf-8", errors="replace") as f:
        return f.read()


def read_bytes(path):
    with open(path, "rb") as f:
        return f.read()


def rel(refs, path):
    return os.path.relpath(path, refs).replace(os.sep, "/")


def walk_files(root):
    out = []
    for dp, dn, fn in os.walk(root):
        dn.sort()
        for f in sorted(fn):
            out.append(os.path.join(dp, f))
    return out


def parse_num(s):
    return int(s, 16) if s.lower().startswith("0x") else int(s, 10)


def strip_code(text):
    text = COMMENT_BLOCK.sub(lambda m: "\n" * m.group(0).count("\n"), text)
    text = COMMENT_LINE.sub("", text)
    return PP_LINE.sub("", text)


class TypeEnv:
    def __init__(self):
        self.alias = {}        # typedef name -> base type text
        self.struct_bodies = {}  # struct typedef name -> body text (in header order)
        self.enums = set()
        self.pfn = {}          # PFN typedef name -> (return text, parameter text)


def parse_nvn_h(raw):
    text = strip_code(raw)
    env = TypeEnv()
    struct_order = []
    for m in STRUCT_TD.finditer(text):
        kind, _tag, body, name = m.groups()
        if kind == "enum":
            env.enums.add(name)
        else:
            if name in env.struct_bodies:
                raise SystemExit("duplicate struct typedef " + name)
            env.struct_bodies[name] = body
            struct_order.append(name)
    for m in ENUM_TAG.finditer(text):
        env.enums.add(m.group(1))
    text2 = STRUCT_TD.sub(";", text)
    for m in PFN_TD.finditer(text2):
        ret, pfn, args = m.groups()
        env.pfn[pfn] = (" ".join(ret.split()), " ".join(args.split()))
        env.alias[pfn] = "void*"
    text3 = PFN_TD.sub(";", text2)
    for m in SIMPLE_TD.finditer(text3):
        base, name = m.groups()
        env.alias[name] = " ".join(base.split())
    return env, struct_order


def tclass(env, text, depth=0):
    """Return the AArch64 class letter for a plain (non-parameter) type spelling."""
    if depth > 20:
        raise ValueError("typedef chain too deep: " + text)
    if "*" in text or "[" in text or "(" in text:
        return "p"
    toks = [x for x in re.findall(r"[A-Za-z_]\w*", text) if x not in QUAL]
    if not toks:
        raise ValueError("empty type: " + repr(text))
    if toks[0] in ("struct", "union"):
        return "S"
    if toks[0] == "enum":
        return "i"
    if len(toks) == 1 and toks[0] in FIXED_L:
        return "l"
    if len(toks) == 1 and toks[0] in FIXED_I:
        return "i"
    if all(t in PRIM for t in toks):
        if toks == ["void"]:
            return "v"
        if "void" in toks:
            raise ValueError("bad void type: " + text)
        if "float" in toks:
            return "f"
        if "double" in toks:
            return "d"
        if "long" in toks:
            return "l"
        return "i"
    if len(toks) == 1:
        n = toks[0]
        if n in env.alias:
            return tclass(env, env.alias[n], depth + 1)
        if n in env.struct_bodies:
            return "S"
        if n in env.enums:
            return "i"
    raise ValueError("unresolved type: " + repr(text))


def known_type_token(env, t):
    return (t in QUAL or t in PRIM or t in FIXED_L or t in FIXED_I or t in env.alias
            or t in env.struct_bodies or t in env.enums)


def param_class(env, p):
    if "*" in p or "[" in p or "(" in p:
        return "p"
    toks = [x for x in re.findall(r"[A-Za-z_]\w*", p) if x not in QUAL]
    # Drop the parameter name when the last word is not a type word.
    if len(toks) >= 2 and not known_type_token(env, toks[-1]):
        p = " ".join(toks[:-1])
    return tclass(env, p)


def split_params(args_text):
    s = " ".join(args_text.split())
    if s in ("", "void"):
        return []
    out, depth, cur = [], 0, ""
    for ch in s:
        if ch == "(":
            depth += 1
        elif ch == ")":
            depth -= 1
        if ch == "," and depth == 0:
            out.append(cur.strip())
            cur = ""
        else:
            cur += ch
    out.append(cur.strip())
    return out


def signature(env, ret_text, args_text):
    ret = "v" if " ".join(ret_text.split()) == "void" else tclass(env, ret_text)
    args = "".join(param_class(env, p) for p in split_params(args_text))
    return ret, args


def parse_funcptr_base(raw, refs_path):
    text = strip_code(raw)
    externs = []
    for m in EXTERN_RE.finditer(text):
        pfn, name = m.group(1), m.group(2)
        expect = "PFNNVN" + name[3:].upper() + "PROC"
        if pfn != expect:
            raise SystemExit("type/name mismatch in %s: %s vs %s" % (refs_path, pfn, name))
        externs.append((name, pfn))
    protos = {}
    for m in PROTO_RE.finditer(text):
        ret, name, args = m.groups()
        protos[name] = (" ".join(ret.split()), " ".join(args.split()))
    return externs, protos


def scalar_size(env, text, depth=0):
    if depth > 20:
        return None
    if "*" in text:
        return 8
    toks = [x for x in re.findall(r"[A-Za-z_]\w*", text) if x not in QUAL]
    if not toks or toks[0] in ("struct", "union"):
        return None
    if toks[0] == "enum":
        return 4
    joined = " ".join(toks)
    if joined in CSIZE:
        return CSIZE[joined]
    if len(toks) == 1:
        n = toks[0]
        if n in env.enums:
            return 4
        if n in env.alias:
            return scalar_size(env, env.alias[n], depth + 1)
    return None


def align_up(v, a):
    return (v + a - 1) // a * a


def struct_layout(env, body):
    """Return (size, kind) or (None, reason)."""
    decls = [" ".join(d.split()) for d in body.split(";") if d.strip()]
    if not decls:
        return None, "empty body"
    if len(decls) == 1:
        m = re.fullmatch(r"(?:unsigned\s+)?char\s+reserved\s*\[\s*(0x[0-9a-fA-F]+|\d+)\s*\]", decls[0])
        if m:
            return parse_num(m.group(1)), "reserved"
    offset, align_max = 0, 1
    for d in decls:
        m = re.fullmatch(r"(.+?)\s+(\w+)\s*(?:\[\s*(0x[0-9a-fA-F]+|\d+)\s*\])?", d)
        if not m:
            return None, "unparsed member: " + d
        base, name, arr = m.group(1), m.group(2), m.group(3)
        count = parse_num(arr) if arr else 1
        size = scalar_size(env, base)
        if size is None:
            return None, "member '%s' type '%s' is not a plain int/float/pointer" % (name, base)
        if re.search(r"\bchar\b", base) and arr and name != "reserved":
            return None, "placeholder char array '%s[%s]'" % (name, arr)
        offset = align_up(offset, size) + size * count
        align_max = max(align_max, size)
    return align_up(offset, align_max), "computed"


def collect_b(refs):
    names = {}
    for rel_dir in SRC_B_DIRS:
        for path in walk_files(os.path.join(refs, rel_dir)):
            for n in set(STR_NVN.findall(read_text(path))):
                names.setdefault(n, rel(refs, path))
    return names


def collect_c(refs, a_set, b_set):
    tokens = {}
    for rel_dir in SRC_C_DIRS:
        for path in walk_files(os.path.join(refs, rel_dir)):
            for t in TOKEN_NVN.findall(read_text(path)):
                tokens.setdefault(t, rel(refs, path))
    known = a_set | b_set | set(C_EXPLICIT) | set(tokens)
    accepted, rejected = {}, []
    explicit_hits = {n: tokens.get(n) for n in C_EXPLICIT}
    for t, f in sorted(tokens.items()):
        if t in a_set or t in b_set or t in C_EXPLICIT:
            continue
        reason = None
        if not re.fullmatch(r"nvn[A-Z][A-Za-z]*", t):
            reason = "not nvn<Name> (digits or underscore)"
        elif any(k != t and k.startswith(t) for k in known):
            reason = "prefix of a longer name (cut off in prose)"
        elif len(re.findall(r"[A-Z][a-z]*", t[3:])) < 2:
            reason = "single word, not nvn<Object><Method>"
        if reason:
            rejected.append((t, f, reason))
        else:
            accepted[t] = f
    return accepted, rejected, explicit_hits


def scan_claims(refs, sizes):
    claims, agree, disagree, lines_out = 0, 0, [], []
    for pat in CLAIM_PATTERNS:
        for path in sorted(glob.glob(os.path.join(refs, pat))):
            for lineno, line in enumerate(read_text(path).splitlines(), 1):
                seen = set()
                for rx in (CLAIM_PAREN, CLAIM_HEX):
                    for m in rx.finditer(line):
                        name = m.group(1)
                        if name not in sizes:
                            continue
                        val = parse_num(m.group(2))
                        if (name, val) in seen:
                            continue
                        seen.add((name, val))
                        claims += 1
                        where = "%s:%d" % (rel(refs, path), lineno)
                        ok = val == sizes[name]
                        agree += ok
                        if not ok:
                            disagree.append((name, sizes[name], val, where))
                        lines_out.append("%s A=0x%X other=0x%X %s %s" % (name, sizes[name], val, where,
                                                                      "agree" if ok else "DISAGREE"))
    return claims, agree, disagree, lines_out


def compare_copies(refs):
    base = os.path.join(refs, SRC_A)
    lines = []
    for d in COPY_DIRS:
        for h in A_HEADERS:
            same = read_bytes(os.path.join(base, h)) == read_bytes(os.path.join(refs, d, h))
            lines.append("%s %s vs practice-mod: %s" % (d.replace(os.sep, "/"), h, "identical" if same else "DIFFERENT"))
        a_files = sorted(os.listdir(os.path.join(base)))
        b_files = sorted(os.listdir(os.path.join(refs, d)))
        diffs = sorted(f for f in set(a_files) & set(b_files)
                       if read_bytes(os.path.join(base, f)) != read_bytes(os.path.join(refs, d, f)))
        only = sorted(set(a_files) ^ set(b_files))
        lines.append("  whole folder: %d files shared, %d differ (%s), only-in-one: %s"
                     % (len(set(a_files) & set(b_files)), len(diffs), ", ".join(diffs) or "none",
                        ", ".join(only) or "none"))
    return lines


def main():
    ap = argparse.ArgumentParser(description=__doc__.split("\n")[0])
    ap.add_argument("--refs", default=DEFAULT_REFS, help="folder containing the reference repos")
    args = ap.parse_args()
    refs = os.path.abspath(args.refs)
    if not os.path.isdir(os.path.join(refs, SRC_A)):
        sys.exit("refs folder not found or missing source A: " + refs)

    # Source A.
    a_dir = os.path.join(refs, SRC_A)
    raw_h = read_text(os.path.join(a_dir, "nvn.h"))
    raw_fp = read_text(os.path.join(a_dir, "nvn_FuncPtrBase.h"))
    env, struct_order = parse_nvn_h(raw_h)
    externs, protos = parse_funcptr_base(raw_fp, "nvn_FuncPtrBase.h")
    a_order = [n for n, _ in externs]
    assert len(a_order) == len(set(a_order)), "duplicate extern names in nvn_FuncPtrBase.h"
    extern_pfn = dict(externs)
    a_set = set(a_order) | set(protos)
    assert not (set(protos) & set(a_order)), "prototype also has extern line"

    # Sources B and C.
    b_map = collect_b(refs)
    b_set = set(b_map)
    c_extra, c_rejected, c_explicit_hits = collect_c(refs, a_set, b_set)
    c_set = set(C_EXPLICIT) | set(c_extra)

    # Full name universe: header order first, then the rest sorted.
    all_names = a_set | b_set | c_set
    order = a_order + sorted(all_names - set(a_order))
    assert len(order) == len(set(order))

    entries = []
    no_sig, via_nvnh, s_funcs, first_arg_bad = [], [], [], []
    for name in order:
        if name in extern_pfn:
            ret_text, args_text = env.pfn[extern_pfn[name]]
            ret, arg_cls = signature(env, ret_text, args_text)
        elif name in protos:
            ret_text, args_text = protos[name]
            ret, arg_cls = signature(env, ret_text, args_text)
        else:
            pfn = "PFNNVN" + name[3:].upper() + "PROC"
            if pfn in env.pfn:
                ret_text, args_text = env.pfn[pfn]
                ret, arg_cls = signature(env, ret_text, args_text)
                via_nvnh.append(name)
            else:
                ret, arg_cls = "?", "?"
                no_sig.append(name)
        if arg_cls not in ("?", "") and arg_cls[0] != "p":
            first_arg_bad.append(name)
        if "S" in ret or "S" in arg_cls.replace("?", ""):
            s_funcs.append(name)
        mask = (1 if name in a_set else 0) | (2 if name in b_set else 0) | (4 if name in c_set else 0)
        entries.append((name, ret, arg_cls, mask))

    # Structs.
    layouts, skipped = [], []
    for name in struct_order:
        size, kind = struct_layout(env, env.struct_bodies[name])
        if size is None:
            skipped.append((name, kind))
        else:
            layouts.append((name, size, kind))
    # The game is the oracle for the size of an object it embeds (debug note 121: the practice mod's header says 0x28 for NVNtextureView,
    # the game keeps its own fields 0x10 bytes after it). Where the game's own code puts the next member of the class that embeds
    # the object, that distance wins (docs/S4e.md, "Struct sizes"). Source mask 8 = the game.
    layouts = [(n, GAME_SIZES.get(n, sz), k) for n, sz, k in layouts]
    sizes = {n: s for n, s, _ in layouts}

    # Write the two .inc files (deterministic).
    table_lines = [
        HEADER,
        "// Columns: NVN_ENTRY(name, ret_class, arg_classes, source_mask)."
        " source_mask: 1=A (nvn_FuncPtrBase.h), 2=B (smo/ssbu runtime), 4=C (explicit list or other refs).",
    ]
    for name, ret, arg_cls, mask in entries:
        arg_txt = '"?"' if arg_cls == "?" else '"%s"' % arg_cls
        table_lines.append("NVN_ENTRY(\"%s\", '%s', %s, %d)" % (name, ret, arg_txt, mask))
    size_lines = [
        HEADER,
        "// Columns: NVN_STRUCT(name, size_bytes, source_mask). source_mask 1=A (nvn.h), 8=the game's own layout.",
    ]
    for name, size, _kind in layouts:
        size_lines.append("NVN_STRUCT(\"%s\", 0x%X, %d)" % (name, size, 8 if name in GAME_SIZES else 1))
    os.makedirs(OUT_DIR, exist_ok=True)
    with open(os.path.join(OUT_DIR, "nvn_table.inc"), "w", encoding="utf-8", newline="\n") as f:
        f.write("\n".join(table_lines) + "\n")
    with open(os.path.join(OUT_DIR, "nvn_sizes.inc"), "w", encoding="utf-8", newline="\n") as f:
        f.write("\n".join(size_lines) + "\n")

    # Self-checks on the written table.
    written = [ln for ln in table_lines if ln.startswith("NVN_ENTRY(")]
    names_written = [re.match(r'NVN_ENTRY\("([^"]+)"', ln).group(1) for ln in written]
    assert len(names_written) == len(set(names_written)), "duplicate names in nvn_table.inc"
    assert len(names_written) == len(entries)
    for n in a_order:
        assert names_written.count(n) == 1, "extern name not exactly once in table: " + n
    assert names_written.count("nvnBootstrapLoader") == 1

    # Report.
    print("NVN table generator")
    print("refs: " + refs)
    print("Source A: %d extern PFN lines (all unique, type/name pairs verified), +%d prototype(s): %s"
          % (len(a_order), len(protos), ", ".join(sorted(protos))))
    print("Source B: %d unique \"nvnXxx\" literals in %s" % (len(b_set), ", ".join(SRC_B_DIRS)))
    print("Source C: %d explicit + %d accepted from grep of %s"
          % (len(C_EXPLICIT), len(c_extra), ", ".join(SRC_C_DIRS)))
    print("  explicit C names seen in the grep (file):")
    for n in C_EXPLICIT:
        print("    %s  <- %s" % (n, c_explicit_hits[n] or "NOT FOUND in grep dirs"))
