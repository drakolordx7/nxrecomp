GAME_SIZES = {"NVNtexture": 0x80, "NVNprogram": 0x80, "NVNsampler": 0x40, "NVNsamplerBuilder": 0x40, "NVNtextureView": 0x10}

HEADER = "// GENERATED by scripts/gen_nvn_table.py from refs (see docs/S4b.md): do not edit"

