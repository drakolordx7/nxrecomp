#!/usr/bin/env python3
"""Generate the NVN entry-point table and the NVN struct-size table from refs.

Outputs (relative to the repo root that contains this scripts/ folder):
  src/gfx/nvn/nvn_table.inc   one NVN_ENTRY(name, ret, args, mask) line per function
  src/gfx/nvn/nvn_sizes.inc   one NVN_STRUCT(name, size, mask) line per struct with a known size

Run:
  python -I scripts/gen_nvn_table.py --refs <path of the refs folder>

Standard library only. Output is deterministic: no timestamps, fixed orders, LF endings.
"""

