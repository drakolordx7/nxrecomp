# Compiles the masked colour clear shaders (GLSL below) with glslc (Vulkan SDK) into src/gfx/nvn/mask_clear_shaders.inc (uint32 arrays).
# The .inc is committed, so building the runtime does not need the SDK. Run: python -I scripts/gen_mask_clear_shaders.py
# The masked clear draws a full-screen triangle whose fragment shader writes one constant colour to one colour output location.
# There is one fragment shader per (kind, location): kind 0 writes vec4 (floats), 1 ivec4 (int32), 2 uvec4 (uint32); location 0..7.
# The colour is read from push constants (16 bytes; the pass reserves 32). A pipeline only enables the colour write mask of its
# own location, so the other channels of that attachment keep their values.
import os, shutil, struct, subprocess, tempfile

root = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
glslc = shutil.which("glslc") or r"C:\VulkanSDK\1.4.363.0\Bin\glslc.exe"

KINDS = (("vec4", 0), ("ivec4", 1), ("uvec4", 2))   # (GLSL type, kind index as used by MaskClear::record)
LOCATIONS = 8

VERT = r"""#version 450
// Full-screen triangle covering the whole clip space; the scissor and viewport given by the pass limit it to the rectangle.
void main() {
    vec2 p = vec2(float((gl_VertexIndex << 1) & 2), float(gl_VertexIndex & 2));
    gl_Position = vec4(p * 2.0 - 1.0, 0.0, 1.0);
}
"""


def frag_text(gtype, loc):
    return ("#version 450\n"
            "// Writes the push-constant colour to colour output %d only (%s).\n"
            "layout(location = %d) out %s o_color;\n"
            "layout(push_constant) uniform PushConstants {\n"
            "    %s value;   // the first 16 bytes of the push constant range\n"
            "} pc;\n"
            "void main() {\n"
            "    o_color = pc.value;\n"
            "}\n") % (loc, gtype, loc, gtype, gtype)


out = ["// GENERATED by scripts/gen_mask_clear_shaders.py from the GLSL in that script: do not edit\n"]
blobs = []   # (array name, C type of the table entry) in table order


def compile_to_words(tmp, name, text, stage):
    src = os.path.join(tmp, name)
    with open(src, "w", newline="\n") as f:
        f.write(text)
    spv = subprocess.run([glslc, "-O", "--target-env=vulkan1.3", "-o", "-", "-fshader-stage=" + stage, src],
                         capture_output=True, check=True).stdout
    return struct.unpack("<%dI" % (len(spv) // 4), spv)


def emit(var, words):
    out.append("static const uint32_t %s[] = {\n" % var)
    for i in range(0, len(words), 8):
        out.append("    " + ", ".join("0x%08x" % w for w in words[i:i + 8]) + ",\n")
    out.append("};\n")


with tempfile.TemporaryDirectory() as tmp:
    emit("kMaskClearVert", compile_to_words(tmp, "mask_clear.vert", VERT, "vert"))
    for gtype, k in KINDS:
        for loc in range(LOCATIONS):
            var = "kMaskClearFrag_k%d_l%d" % (k, loc)
            emit(var, compile_to_words(tmp, "mask_clear_k%d_l%d.frag" % (k, loc), frag_text(gtype, loc), "frag"))

# Table: kMaskClearFrag[kind][location] -> blob. ShaderBlob is declared by the .cpp that includes this file.
out.append("\nstatic const ShaderBlob kMaskClearFrag[3][8] = {\n")
for gtype, k in KINDS:
    out.append("    {\n")
    for loc in range(LOCATIONS):
        var = "kMaskClearFrag_k%d_l%d" % (k, loc)
        out.append("        {%s, sizeof %s},\n" % (var, var))
    out.append("    },\n")
out.append("};\n")
out.append("static const ShaderBlob kMaskClearVertBlob = {kMaskClearVert, sizeof kMaskClearVert};\n")

with open(os.path.join(root, "src", "gfx", "nvn", "mask_clear_shaders.inc"), "w", newline="\n") as f:
    f.write("".join(out))
print("wrote mask_clear_shaders.inc")
