"""Compiler launcher for lifted code: a bounded-time rule for huge functions.

    python nx_cc_launcher.py <compiler> <compiler args...>      (CMake: CXX_COMPILER_LAUNCHER, option NX_USE_LAUNCHER)

Adapted from smo-recomp tools/lifter/build_main.py (GPL-3.0-or-later; the rule itself is ssbu-recomp's build_opt.py):
  1. the lifter already emits NX_OPTNONE (optnone, noinline) on functions over the game config's optnone_insns;
  2. a translation unit that still takes longer than NX_TIME_LIMIT seconds (default 180) is retried with every function of
     more than limit/4 statements declared optnone through a generated -include header, then limit/16;
  3. then the whole file at -O0 (/Od).
Environment: NX_TIME_LIMIT (seconds), NX_OPTNONE_LINES (the first statement limit, default 20000).
The launcher only wraps compiles of c_*.cpp files of generated modules; everything else runs unchanged.
"""
import os
import re
import subprocess
import sys
import tempfile
import time

TIME_LIMIT = float(os.environ.get('NX_TIME_LIMIT', '180'))
OPTNONE_LINES = int(os.environ.get('NX_OPTNONE_LINES', '20000'))
DEF = re.compile(r'^(?:NX_OPTNONE |__attribute__\(\(noinline\)\) )?void ([fu]_[0-9a-f]+)\((Ctx \*__restrict c(?:, uint64_t rp)?)\) \{$')


def function_sizes(path):
    out, cur, n = [], None, 0
    with open(path, encoding='latin-1') as f:
        for line in f:
            if cur is None:
                m = DEF.match(line.rstrip('\n'))
                if m:
                    cur, n = (m.group(1), m.group(2)), 0
            elif line.startswith('}'):
                out.append((n, cur[0], cur[1]))
                cur = None
            else:
                n += 1
    return out


def run(cmd, limit):
    t = time.time()
    p = subprocess.Popen(cmd)
    try:
        return p.wait(timeout=limit), time.time() - t
    except subprocess.TimeoutExpired:
        subprocess.run(['taskkill', '/PID', str(p.pid), '/T', '/F'], capture_output=True)
        p.wait()
        return None, time.time() - t


def main():
    cmd = sys.argv[1:]
    src = next((a for a in cmd if re.search(r'[\\/]c_\d+\.cpp$|[\\/]c_[0-9a-f]+\.cpp$', a)), None)
    if not src:
        sys.exit(subprocess.call(cmd))
    for limit in (OPTNONE_LINES, OPTNONE_LINES // 4, OPTNONE_LINES // 16):
        big = [(n, name, params) for n, name, params in function_sizes(src) if n > limit]
        extra = []
        hdr = None
        if big and limit != OPTNONE_LINES:
            hdr = tempfile.NamedTemporaryFile('w', suffix='.h', delete=False)
            hdr.write('/* generated by nx_cc_launcher.py: functions too long to optimise in bounded time */\n#include <nxrecomp/ctx.h>\nextern "C" {\n')
            for n, name, params in big:
                hdr.write('void %s(%s) __attribute__((optnone, noinline));\n' % (name, params))
            hdr.write('}\n')
            hdr.close()
            extra = ['/clang:-include', '/clang:' + hdr.name.replace(chr(92), '/')] if 'cl' in os.path.basename(cmd[0]).lower() and 'clang++' not in cmd[0].lower() else ['-include', hdr.name]
        elif limit != OPTNONE_LINES:
            continue
        code, secs = run(cmd + extra, TIME_LIMIT)
        if hdr:
            os.unlink(hdr.name)
        if code is not None:
            if extra:
                print('nx_cc_launcher: %s: %d function(s) over %d statements compiled unoptimised' % (os.path.basename(src), len(big), limit), file=sys.stderr)
            sys.exit(code)
        print('nx_cc_launcher: %s exceeded %.0fs; retrying with a lower optnone limit' % (os.path.basename(src), TIME_LIMIT), file=sys.stderr)
    low = [('/Od' if a in ('/O1', '/O2', '-O1', '-O2') else a) for a in cmd]
    print('nx_cc_launcher: %s: whole file unoptimised' % os.path.basename(src), file=sys.stderr)
    sys.exit(subprocess.call(low))


if __name__ == '__main__':
    main()
