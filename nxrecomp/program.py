"""The program level of the lifter: function discovery -> one C++ function per guest function -> sharded sources.

Adapted from smo-recomp tools/lifter/recomp.py (GPL-3.0-or-later: Env, lift_function, cmd_full2, cmd_cover), with:
  * an `Image` (image.py) in place of module globals, so several modules lift in one process and tests lift ELFs;
  * a per-game `GameConfig` (config.py) in place of SMO-specific rules;
  * C++ landing-pad resume entries (`u_<entry>(c, rp)`), after ssbu-recomp tools/lifter/recomp_eh.py (GPL-3.0-or-later);
  * jump tables resolved to bounded switches (jumptables.py, after SuperMarioWonderRecomp's resolver, MIT);
  * output sharded into a fixed number of translation units (for CMake) or by guest address (for stable files);
  * a module descriptor `nxmod_<name>` (ctx.h: NxModule) instead of smo's loose tables.

Generated files, in <outdir>:
    c_<NNN>.cpp   the lifted functions (shards)        funcs.h     declarations of every f_<addr> / u_<addr>
    module_<name>.cpp   function table, dynamic symbols, resume table, unwind tables  (the NxModule)
"""
import bisect
import collections
import multiprocessing
import os
import struct
import sys
import time

from .image import Image
from .lift import Lifter, Fn, Unimpl, bits, sext
from . import eh as ehmod

GEN_HEADER = '/* generated by nxrecomp -- do not edit */\n#include <nxrecomp/cxx.h>\n#include "funcs.h"\n\n'


def mangle(name):
    return ''.join(ch if ch.isalnum() else '_' for ch in name)


# ---------------------------------------------------------------------------------------------------- patches
def load_patches(path, img):
    """Instruction patches: one `<address> <original word> <new word>  # note` per line (hex). The original word is
    checked against the image. Returns {address: new word}."""
    out = {}
    with open(path) as f:
        for line in f:
            t = line.split('#', 1)[0].split()
            if not t:
                continue
            addr, old, new = int(t[0], 16), int(t[1], 16), int(t[2], 16)
            have = img.word(addr)
            if have != old:
                raise ValueError('patch %x: the binary has %08x, the patch expects %08x' % (addr, have, old))
            out[addr] = new
    return out


# ---------------------------------------------------------------------------------------------------- Env
class Env:
    """Per-module lifting state: the image, function extents, imports (PLT), jump tables, landing pads."""

    def __init__(self, img, cfg=None, full=True):
        from .config import GameConfig
        self.img = img
        self.cfg = cfg or GameConfig()
        self.base = img.base
        self.text_lo = img.base + img.text_start
        self.text_hi = self.text_lo + img.text_size
        self.full = full
        self.wanted = collections.OrderedDict()
        self.overrides = dict(self.cfg.overrides)
        self.imports = set()
        self.plt_cache, self.plt_slot = {}, {}
        self.plt_syms = None
        self.patches = {}
        self.ends = {}
        self.starts = []
        self.jt = {}                  # address of a `br` -> sorted list of target addresses (jumptables.py)
        self.pads = []                # sorted landing pad addresses
        self.catchers = set()         # entries of functions entered through nx_catch_call
        self.eh_starts = set()        # entries of functions that have an LSDA
        self._syms = None

    # ---- words
    def word(self, addr):
        if self.patches and addr in self.patches:
            return self.patches[addr]
        return self.img.word(addr)

    # ---- imports through the PLT
    def load_plt(self):
        self.plt_syms, self.plt_info = {}, {}
        syms = self.img.symbols()
        for off, info, _ in self.img.jmprel():
            idx = info >> 32
            name, typ, bind, shndx, value, size = syms[idx]
            slot = self.base + off if off < self.base else off
            self.plt_syms[slot] = name
            self.plt_info[slot] = (idx, shndx, value)

    def plt_symbol(self, target):
        """If target is a PLT stub (adrp x16 / ldr x17 / add x16 / br x17), the imported symbol's name."""
        if target in self.plt_cache:
            return self.plt_cache[target]
        name = None
        if target + 16 <= self.text_hi and target >= self.text_lo and 23 in self.img.dt:
            w0, w1, w2, w3 = (self.word(target + i) for i in (0, 4, 8, 12))
            if (w0 & 0x9f00001f) == 0x90000010 and (w1 & 0xffc003ff) == 0xf9400211 and w3 == 0xd61f0220:
                if self.plt_syms is None:
                    self.load_plt()
                page = (target & ~0xfff) + (sext((bits(w0, 23, 5) << 2) | bits(w0, 30, 29), 21) << 12)
                name = self.plt_syms.get(page + bits(w1, 21, 10) * 8)
                if name is not None:
                    self.plt_slot[target] = page + bits(w1, 21, 10) * 8
        self.plt_cache[target] = name
        return name

    def plt_entry(self, target):
        """(symbol index, section index, value) when target is a PLT stub, else None."""
        if self.plt_symbol(target) is None:
            return None
        return self.plt_info[self.plt_slot[target]]

    # ---- direct calls
    def call(self, target):
        if target in self.overrides:
            return 'h_%s(c);' % self.overrides[target]
        if not (self.text_lo <= target < self.text_hi):
            return 'call_indirect(c, 0x%xULL);' % target          # another module / not code of this one
        self.wanted.setdefault(target, None)
        return 'f_%x(c);' % target

    # ---- function list
    def compute_starts(self, extra=()):
        """Function entries and exact ends: funcs.analyse(img) plus the config's extra entries (module offsets)."""
        from . import funcs
        rows, self.stats = funcs.analyse(self.img)
        self.ends = {}
        for r in rows:
            self.ends[self.base + r['start']] = self.base + r['end']
        for off in list(self.cfg.extra_entries.get(self.img.name, ())) + list(extra):
            a = self.base + off
            if a not in self.ends:
                self.ends[a] = self.base + off + 4
        self.starts = sorted(self.ends)
        # an extra entry splits the function it falls into: keep that function's end as is
        return self.starts

    def extent(self, entry):
        if entry in self.ends:
            return self.ends[entry]
        i = bisect.bisect_right(self.starts, entry)
        return self.starts[i] if i < len(self.starts) else self.text_hi

    # ---- exception data
    def load_eh(self):
        """Landing pads and the functions that need nx_catch_call, from the LSDAs."""
        rd = ehmod.Reader(self.img)
        fdes, cies = ehmod.all_fdes(self.img)
        pads, catchers, starts = set(), set(), set()
        self.eh_data = {}
        for f in fdes:
            if not f.lsda:
                continue
            sites, actions, types = ehmod.parse_lsda(rd, self.img, f)
            entry = self.base + f.start
            starts.add(entry)
            self.eh_data[entry] = (f, sites, actions, types)
            for s in sites:
                if not s.pad:
                    continue
                pad = self.base + s.pad
                pads.add(pad)
                a, has_catch = s.action, False
                while a:
                    filt, nxt = actions[a]
                    if filt > 0:
                        has_catch = True
                    a = nxt
                if has_catch and not self._terminate_pad(pad):
                    catchers.add(entry)
        self.pads = sorted(pads)
        self.catchers = catchers
        self.eh_starts = starts
        return fdes

    def _terminate_pad(self, pad):
        """A catch(...) pad that only calls __clang_call_terminate (a noexcept boundary): bl __cxa_begin_catch; bl terminate."""
        def bl_target(a):
            w = self.word(a)
            if (w & 0xfc000000) != 0x94000000:
                return None
            return a + sext(w & 0x3ffffff, 26) * 4
        t = None
        for i in range(2):
            t = bl_target(pad + 4 * i)
            if t:
                break
        if not t:
            return False
        names = []
        for i in range(6):
            x = bl_target(t + 4 * i)
            if x:
                names.append(self.symbol_name(x))
        return names[:2] == ['__cxa_begin_catch', '_ZSt9terminatev']

    def symbol_name(self, addr):
        n = self.plt_symbol(addr)
        if n:
            return n
        if self._syms is None:
            self._syms = {}
            for name, typ, bind, shndx, value, size in self.img.symbols():
                if shndx and name:
                    self._syms.setdefault(self.base + self.img.sym_value(value) if self.img.symtab_is_dynamic else value, name)
        return self._syms.get(addr)


# ---------------------------------------------------------------------------------------------------- one function
TAILS = ('return;', 'goto', '{ jt', '{ f_', '{ h_', '{ call_indirect', 'switch (', '{ nx_')


def lift_function(env, entry):
    """-> (text, instruction count, [(pc, word, reason)], [(pad, entry)])."""
    img = env.img
    if env.full and env.plt_entry(entry):
        sym, shndx, value = env.plt_entry(entry)
        if shndx:                                    # symbol defined inside this module
            tgt = env.base + value
            env.wanted.setdefault(tgt, None)
            return 'void f_%x(Ctx *__restrict c) { f_%x(c); }' % (entry, tgt), 0, [], []
        env.imports.add(env.plt_symbol(entry))
        return 'void f_%x(Ctx *__restrict c) { host_import(c, %d); }' % (entry, sym), 0, [], []
    end = env.extent(entry)
    fn = Lifter(entry, end, env)
    lines, bad = [], []
    pc = entry
    while pc < end:
        w = env.word(pc)
        try:
            stmt = fn.lift(w, pc)
        except Unimpl as e:
            stmt = 'guest_unimpl(0x%xULL, 0x%08xU, "%s");' % (pc, w, str(e).replace('"', "'"))
            bad.append((pc, w, str(e)))
        lines.append((pc, stmt))
        pc += 4
    pads = env.pads[bisect.bisect_left(env.pads, entry):bisect.bisect_left(env.pads, end)]
    two = bool(pads) or entry in env.catchers
    cold = ''
    if len(lines) > env.cfg.optnone_insns:
        cold = 'NX_OPTNONE '
    out = ['%svoid %s_%x(Ctx *__restrict c%s) {' % (cold, 'u' if two else 'f', entry, ', uint64_t rp' if two else ''),
           '  c->fn = 0x%xULL;' % entry]
    if fn.has_br_fallback:
        out.append('  uint64_t jt = 0;')
    if pads:
        out.append('  if (rp) switch (rp) {')
        out.extend('  case 0x%xULL: goto L_%x;' % (lp, lp) for lp in pads)
        out.append('  default: guest_trap("resume at an address that is not a landing pad of this function", rp); return; }')
    needed = set(fn.targets) | set(pads)
    if fn.has_br_fallback:
        needed = {pc for pc, _ in lines}
    for pc, stmt in lines:
        out.append(('L_%x: %s' % (pc, stmt)) if pc in needed else '  ' + stmt)
    last = lines[-1][1]
    ends_open = not last.startswith(TAILS)
    listed = env.ends
    if ends_open and end < env.text_hi and end in listed:
        out.append('  f_%x(c); return;' % end)           # falls through into the next listed function
        env.wanted.setdefault(end, None)
    elif ends_open:
        out.append('  guest_trap("fell off the end of a function", 0x%xULL); return;' % end)
    else:
        out.append('  return;')
    if fn.has_br_fallback:
        out.append('L_dispatch: switch (jt) {')
        out.extend('  case 0x%xULL: goto L_%x;' % (pc, pc) for pc, _ in lines)
        out.append('  default: call_indirect(c, jt); return; }')
    out.append('}')
    if two:
        out.append('void f_%x(Ctx *__restrict c) { %s }' % (entry, 'nx_catch_call(c, u_%x);' % entry if entry in env.catchers else 'u_%x(c, 0);' % entry))
    return '\n'.join(out), len(lines), bad, [(lp, entry) for lp in pads]


# ---------------------------------------------------------------------------------------------------- whole module
def make_env(spec):
    """Rebuild an Env in a worker from a picklable spec."""
    img = open_image(spec)
    from .config import load_game
    cfg = load_game(spec.get('game'))
    env = Env(img, cfg)
    if spec.get('patches'):
        env.patches = load_patches(spec['patches'], img)
    env.ends = dict(spec['ends'])
    env.starts = sorted(env.ends)
    env.jt = {int(k): v for k, v in spec['jt'].items()}
    env.pads = spec['pads']
    env.catchers = set(spec['catchers'])
    env.full = True
    return env


def open_image(spec):
    k = spec['kind']
    if k == 'nso':
        return Image.from_nso(open(spec['path'], 'rb').read(), spec['base'], spec['name'])
    if k == 'nx_elf':
        return Image.from_nx_elf(spec['path'], spec['base'], spec['name'])
    return Image.from_static_elf(spec['path'], spec['name'])


_worker_env = None


def _worker_init(spec):
    global _worker_env
    _worker_env = make_env(spec)


def _worker_scan(entries):
    env = _worker_env
    env.wanted = collections.OrderedDict()
    total = bad = 0
    for a in entries:
        _, n, b, _ = lift_function(env, a)
        total += n
        bad += len(b)
    return total, bad, list(env.wanted)


def _worker_text(entries):
    env = _worker_env
    env.wanted = collections.OrderedDict()
    texts, resume, insns = [], [], 0
    for a in entries:
        t, n, _, r = lift_function(env, a)
        texts.append(t)
        resume += r
        insns += n
    return '\n\n'.join(texts), resume, insns


def _write_if_changed(path, content):
    if os.path.exists(path):
        with open(path, encoding='utf-8', newline='') as f:
            if f.read() == content:
                return False
    with open(path, 'w', encoding='utf-8', newline='\n') as f:
        f.write(content)
    return True


def lift_module(spec, outdir, jobs=8, shards=0, bucket=0xC000, log=print):
    """Lift every function of the module described by `spec` into outdir.
    spec: dict(kind, path, base, name, game, patches). shards > 0: exactly that many c_NNN.cpp files (balanced by
    instruction count, contiguous in address order); shards == 0: one c_<bucket>.cpp per `bucket` bytes of guest code."""
    from .config import load_game
    t0 = time.time()
    img = open_image(spec)
    cfg = load_game(spec.get('game'))
    env = Env(img, cfg)
    if spec.get('patches'):
        env.patches = load_patches(spec['patches'], img)
    env.compute_starts()
    env.load_eh()
    from . import jumptables
    jumptables.resolve(env)
    starts = env.starts
    log('%s: %d function entries, %d landing pads, %d jump tables  (%.1fs)' % (img.name, len(starts), len(env.pads), len(env.jt), time.time() - t0))
    spec = dict(spec, ends=env.ends, jt={str(k): v for k, v in env.jt.items()}, pads=env.pads, catchers=sorted(env.catchers))
    os.makedirs(outdir, exist_ok=True)
    known = set(starts)
    pending = list(starts)
    all_funcs, total, bad = [], 0, 0
    pool = multiprocessing.Pool(jobs, _worker_init, (spec,)) if jobs > 1 else None
    if pool is None:
        _worker_init(spec)
    try:
        mapper = pool.imap_unordered if pool else map
        # discovery: lifting finds branch targets that are not listed functions (tail calls, fall-through ends)
        while pending:
            pending.sort()
            parts = [pending[i:i + 400] for i in range(0, len(pending), 400)]
            new = set()
            for n, b, wanted in mapper(_worker_scan, parts):
                total += n
                bad += b
                new.update(w for w in wanted if w not in known and env.text_lo <= w < env.text_hi)
            all_funcs += pending
            log('discovery: %d functions, %d extra branch targets  (%.1fs)' % (len(pending), len(new), time.time() - t0))
            known |= new
            for w in new:
                if w not in env.ends:
                    env.ends[w] = env.extent(w)          # extent by next start, as a worker would compute it
            pending = list(new)
        all_funcs.sort()
        # workers must know the new entries too (their extents are by the next start): rebuild the spec
        if len(all_funcs) != len(starts):
            spec['ends'] = {a: env.ends.get(a, env.extent(a)) for a in all_funcs}
            if pool:
                pool.close()
                pool = multiprocessing.Pool(jobs, _worker_init, (spec,))
                mapper = pool.imap_unordered
            else:
                _worker_init(spec)
        # shard assignment
        sizes = {a: max(1, (spec['ends'][a] - a) // 4) for a in all_funcs}
        groups = collections.OrderedDict()
        if shards:
            target = sum(sizes.values()) / float(shards)
            k, acc = 0, 0
            for a in all_funcs:
                if acc >= target and k < shards - 1:
                    k, acc = k + 1, 0
                groups.setdefault(k, []).append(a)
                acc += sizes[a]
            names = {k: 'c_%03d.cpp' % k for k in range(shards)}
            for k in range(shards):
                groups.setdefault(k, [])
        else:
            for a in all_funcs:
                groups.setdefault((a - env.base) // bucket, []).append(a)
            names = {k: 'c_%04x.cpp' % k for k in groups}
        jobs_list = [(k, v) for k, v in groups.items()]
        resume, files, changed, insns = [], [], 0, 0
        for (k, entries), (text, res, n) in zip(jobs_list, map_ordered(pool, _worker_text, [v for _, v in jobs_list])):
            resume += res
            insns += n
            content = GEN_HEADER + text + '\n'
            files.append(names[k])
            changed += _write_if_changed(os.path.join(outdir, names[k]), content)
    finally:
        if pool:
            pool.close()
    first = {}
    for lp, e in sorted(resume):
        first.setdefault(lp, e)
    resume = sorted(first.items())
    catchers = sorted(a for a in env.catchers if a in set(all_funcs))
    write_module_files(env, outdir, all_funcs, resume, catchers)
    keep = set(files) | {'funcs.h', 'module_%s.cpp' % img.name}
    for n in os.listdir(outdir):
        if (n.endswith('.cpp') and n.startswith('c_')) and n not in keep:
            os.remove(os.path.join(outdir, n))
    log('%s: functions %d   files %d (%d rewritten)   instructions %d   not translated %d   (%.1fs)'
        % (img.name, len(all_funcs), len(files), changed, insns, bad, time.time() - t0))
    return {'functions': len(all_funcs), 'files': files, 'instructions': insns, 'not_translated': bad}


def map_ordered(pool, fn, items):
    return pool.map(fn, items) if pool else [fn(i) for i in items]


def write_module_files(env, outdir, all_funcs, resume, catchers):
    img = env.img
    name = mangle(img.name)
    nsym = img.nsym if img.symtab_is_dynamic else 0
    u_entries = sorted(set(e for _, e in resume) | set(catchers))
    h = ['/* generated by nxrecomp -- do not edit */', '#ifndef NXRECOMP_FUNCS_H', '#define NXRECOMP_FUNCS_H',
         '#include <nxrecomp/ctx.h>', '#ifdef __cplusplus', 'extern "C" {', '#endif',
         '#define NX_OPTNONE __attribute__((optnone, noinline))']
    h += ['void f_%x(Ctx *__restrict c);' % a for a in all_funcs]
    h += ['void u_%x(Ctx *__restrict c, uint64_t rp);' % a for a in u_entries]
    h += ['void h_%s(Ctx *c);' % n for n in sorted(set(env.overrides.values()))]
    h += ['#ifdef __cplusplus', '}', '#endif', '#endif', '']
    _write_if_changed(os.path.join(outdir, 'funcs.h'), '\n'.join(h))
    m = ['/* generated by nxrecomp -- do not edit */', '#include <nxrecomp/ctx.h>', '#include "funcs.h"', '',
         'extern "C" {', 'static const FnEntry fns[] = {']
    m += ['  { 0x%xULL, f_%x },' % (a, a) for a in all_funcs]
    for a, n in sorted(env.overrides.items()):
        m.append('  { 0x%xULL, h_%s },' % (a, n))
    m.append('};')
    m.append('static const DynSym syms[] = {')
    allsyms = img.symbols() if nsym else []
    for i in range(nsym):
        sname, typ, bind, shndx, value, size = allsyms[i]
        m.append('  { "%s", 0x%xULL, %d },' % (sname.replace('\\', '\\\\').replace('"', '\\"'), value, 1 if shndx else 0))
    if not nsym:
        m.append('  { "", 0, 0 },')
    m.append('};')
    m.append('static const NxResume resume[] = {')
    m += ['  { 0x%xULL, u_%x },' % (lp, e) for lp, e in resume]
    if not resume:
        m.append('  { 0, 0 },')
    m.append('};')
    eh_name = emit_eh_tables(env, m)
    m.append('extern const NxModule nxmod_%s;' % name)
    m.append('const NxModule nxmod_%s = { "%s", 0x%xULL, 0x%xULL, fns, %d, syms, %d, resume, %d, %s };'
             % (name, img.name, env.base, env.text_hi, len(all_funcs) + len(env.overrides), nsym, len(resume), eh_name))
    m.append('}')
    m.append('')
    _write_if_changed(os.path.join(outdir, 'module_%s.cpp' % name), '\n'.join(m))


def img_sym(img, i):
    name_off, info, other, shndx, value, size = struct.unpack_from('<IBBHQQ', img.mem, img.sym_off + i * 24)
    return img.cstr(img.str_off + name_off), info & 0xf, info >> 4, shndx, value, size


def emit_eh_tables(env, m):
    """Append the NxEh tables of the module to m (unwind rows, call sites, actions, types) -> expression for NxModule.eh."""
    from . import ehtables
    return ehtables.emit(env, m)


# ---------------------------------------------------------------------------------------------------- coverage
def cover(img, cfg=None, log=print, limit_examples=3):
    """Per-instruction-word translation coverage of .text, with the reasons for what is not translated."""
    env = Env(img, cfg)
    fn = Lifter(img.base, img.end, env)
    ok = bad = 0
    reasons = collections.Counter()
    examples = {}
    cache = {}
    for i, w in enumerate(img.words()):
        r = cache.get(w)
        if r is None:
            try:
                fn.lift(w, env.text_lo + 0x1000000)
                r = ''
            except Unimpl as e:
                r = str(e)
            except Exception as e:                       # a decoder bug counts as not translated
                r = 'error:%s' % type(e).__name__
            cache[w] = r
        if r:
            bad += 1
            reasons[r] += 1
            examples.setdefault(r, '%x:%08x' % (env.text_lo + 4 * i, w))
        else:
            ok += 1
    total = ok + bad
    log('instruction words: %d   translated: %d (%.2f%%)   not translated: %d (%.2f%%)'
        % (total, ok, 100.0 * ok / max(1, total), bad, 100.0 * bad / max(1, total)))
    for r, n in reasons.most_common(30):
        log('  %-16s %9d  %.2f%%   e.g. %s' % (r, n, 100.0 * n / total, examples[r]))
    return ok, bad, reasons
